/**
 * Наценка на доставку СДЭК — чтобы магазин всегда был в плюсе.
 *
 * Зачем. Цепочка ценообразования была такая:
 *     расчёт СДЭК → округление вверх до 100 ₽ (сниппет 70)
 *                 → нижняя граница 400/500/600 ₽ (сниппет 133)
 * То есть весь запас магазина — это остаток от округления, от 0 до 99 ₽.
 * На дальнем городе, где расчёт выходит, скажем, 1240 ₽, покупатель платит
 * 1300 ₽, и запас всего 60 ₽. Любая неточность в заявленном весе или
 * габаритах этот запас съедает, и разницу доплачивает магазин.
 *
 * Здесь добавляется явный процент поверх расчёта СДЭК. Работает ДО
 * округления (приоритет 90 против 100 у сниппета 70), поэтому итог всё
 * равно уходит вверх до ближайшей сотни, а нижняя граница применяется
 * последней и ничего не ломает.
 *
 * Распоряжение владельца 22.09.2026: «надо проверить, чтобы я был всегда
 * в плюсе в доставке, то есть закладывать доставку выше, чем она есть
 * в СДЭКе».
 *
 * ЧТОБЫ ИЗМЕНИТЬ РАЗМЕР НАЦЕНКИ — правьте одно число ниже.
 */
if ( ! defined( 'WAYSTEA_CDEK_MARKUP' ) ) {
    define( 'WAYSTEA_CDEK_MARKUP', 1.15 );   // 1.15 = +15 %
}

add_filter( 'woocommerce_package_rates', function ( $rates ) {
    foreach ( $rates as $rate ) {
        if ( strpos( $rate->get_method_id(), 'official_cdek' ) !== 0 ) {
            continue;
        }
        $cost = (float) $rate->get_cost();
        if ( $cost > 0 ) {
            $rate->set_cost( (string) round( $cost * WAYSTEA_CDEK_MARKUP, 2 ) );
        }
    }
    return $rates;
}, 90 );
