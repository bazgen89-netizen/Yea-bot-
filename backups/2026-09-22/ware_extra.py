# ------------------------------------------------------- какой чай под этот объём

def pairing(kind, v, mat):
    """Подбор чая под объём и материал. Для каждой полосы объёма — свой текст."""
    if kind not in ('гайвань', 'пиала', 'чайник') or not v:
        return ''
    h = '<h2>Какой чай под этот объём</h2>'

    if kind == 'пиала':
        if v <= 45:
            return h + ('<p>Совсем малая пиала — под самые плотные настои: шу пуэр, '
                        'тёмный улун сильной обжарки, выдержанный хэй ча. Такой чай '
                        'пьют по глотку, вдумчиво, и большая порция здесь только мешает. '
                        'Из этой пиалы настой не успевает потерять температуру, '
                        'а значит и верхние ноты аромата.</p>')
        if v <= 60:
            return h + ('<p>Классический гунфу-объём. Под улуны — Те Гуань Инь, Да Хун Пао, '
                        'Алишань, — под шу и шэн пуэр, под красный чай. Именно на этом '
                        'размере построено многопроливное заваривание: один пролив гайвани '
                        'делится на три-четыре такие пиалы, и каждый следующий отличается '
                        'от предыдущего.</p>')
        if v <= 90:
            return h + ('<p>Объём побольше прощает невнимательность: чай не кончается '
                        'после второго глотка. Хорош под красный чай и Дянь Хун, под белый '
                        'Бай Му Дань, под шу пуэр. Для деликатного зелёного тоже годится — '
                        'ему как раз полезно чуть остыть в пиале.</p>')
        if v <= 130:
            return h + ('<p>Это уже чаша для спокойного чаепития, а не для гунфу. '
                        'Под неё — красный чай, выдержанный шу пуэр, травяные сборы, '
                        'Габа. То есть всё, что не портится, остывая, и не требует '
                        'слить настой в первые двадцать секунд.</p>')
        return h + ('<p>Большая чаша — под долгий чай: красный, шу пуэр, каркаде, '
                    'саган-дайля, маття. Улун и шэн пуэр в такой посуде теряют смысл: '
                    'их вкус меняется от пролива к проливу, а здесь всё смешивается '
                    'в одну большую порцию.</p>')

    if kind == 'гайвань':
        if v <= 120:
            return h + (f'<p>{v} мл — закладка 5–6 г. Под этот объём особенно хороши '
                        'зелёный и белый чай: малая чаша быстрее отдаёт тепло, а им '
                        'перегрев вредит. Улуны и красный чай заваривать тоже удобно, '
                        'просто проливы будут чаще.</p>')
        if v <= 160:
            return h + (f'<p>{v} мл — закладка 6–8 г, рабочий объём под что угодно. '
                        'Улуны раскрываются полностью: шарикам Те Гуань Инь и Алишаня '
                        'нужно место, чтобы развернуться, и в тесной чаше они '
                        'разворачиваются не до конца. Пуэр, красный, белый — тоже без '
                        'оговорок.</p>')
        return h + (f'<p>{v} мл — закладка 8–10 г. Объём под прессованный чай: '
                    'отломанный кусок пуэрного блина занимает много места и в малой '
                    'гайвани просто не помещается. Для зелёного великовата — он успеет '
                    'перестоять, пока вы разливаете.</p>')

    # чайник
    if mat in ('исин', 'глина'):
        if v <= 150:
            return h + ('<p>Малый глиняный чайник — под один определённый чай, '
                        'который вы пьёте постоянно. Чаще всего под шу пуэр или тёмный '
                        'улун: они дают патину быстрее всего и лучше всех отзываются '
                        'на то, что глина держит тепло.</p>')
        return h + ('<p>Глина держит температуру, и это решает для чаёв, которые '
                    'заваривают крутым кипятком: шу пуэр, выдержанный шэн, тёмный улун, '
                    'лю бао. Зелёный и белый в глиняном чайнике заваривать не стоит — '
                    'им нужна вода попрохладнее, а стенка не даст ей остыть.</p>')
    if mat == 'стекло':
        return h + ('<p>Стекло показывает чай, поэтому в нём особенно хороши те сорта, '
                    'на которые интересно смотреть: связанные цветущие чаи, белый '
                    'Бай Хао Инь Чжэнь с серебряными почками, зелёный с крупным листом. '
                    'Вкус стекло не меняет вовсе — это честный сосуд для дегустации.</p>')
    if v and v <= 150:
        return h + ('<p>Фарфор ничего не впитывает, поэтому чайник годится под любой чай '
                    'без закрепления за сортом. Малый объём — под улуны и красный чай '
                    'короткими проливами.</p>')
    return h + ('<p>Фарфор и глазурь нейтральны: сегодня зелёный, завтра пуэр — вкус '
                'не смешается. Объём рассчитан на компанию, поэтому удобнее всего '
                'заваривать то, что пьют помногу: красный чай, шу пуэр, травяные сборы.</p>')


# --------------------------------------------- сравнение с соседними размерами

def peers(x, kind, v, all_same_kind):
    """Абзац о том, какие ещё размеры того же предмета есть в магазине.
    Берётся из реальных данных каталога, а не сочиняется."""
    if not v:
        return ''
    others = sorted({o for o in all_same_kind if o and o != v})
    if len(others) < 2:
        return ''
    smaller = [o for o in others if o < v][-2:]
    bigger = [o for o in others if o > v][:2]
    if not smaller and not bigger:
        return ''
    s = ['<h2>Если этот размер не подходит</h2>', '<p>']
    s.append(f'В магазине есть и другие объёмы того же назначения. ')
    if smaller:
        s.append('Меньше — ' + ', '.join(f'{o} мл' for o in smaller) + ': ')
        s.append('порция выходит камернее, чай остаётся горячим до последнего глотка. ')
    if bigger:
        s.append('Больше — ' + ', '.join(f'{o} мл' for o in bigger) + ': ')
        s.append('удобнее, когда за столом больше людей или чай пьют долго. ')
    s.append(f'Этот — на {v} мл.</p>')
    return ''.join(s)


# ------------------------------------------------------------------ про цену

def price_note(kind, price, mat, dec):
    """Честный абзац о том, за что цена. Без оценок вроде «премиум-качество»."""
    try:
        p = float(price)
    except (TypeError, ValueError):
        return ''
    hand = any('ручн' in d for d in dec)
    h = '<h2>За что цена</h2>'
    if p >= 6000:
        base = ('Это верхняя часть ассортимента. В такой цене обычно сходятся '
                'три вещи: материал, ручной труд и размер. ')
        if hand:
            base += ('Ручная роспись не тиражируется — двух совершенно одинаковых '
                     'предметов не бывает, мелкие отличия рисунка это норма, а не брак. ')
        if mat in ('исин', 'глина'):
            base += ('Глиняная посуда дорожает с возрастом в буквальном смысле: '
                     'чем дольше ей пользуются, тем она лучше. ')
        return h + f'<p>{base}</p>'
    if p >= 2000:
        base = 'Средняя цена по ассортименту — рабочая вещь на каждый день. '
        if hand:
            base += 'Роспись ручная, поэтому мелкие расхождения рисунка между экземплярами естественны. '
        base += 'Такую посуду не жалко брать в постоянное пользование, а не прятать в сервант.'
        return h + f'<p>{base}</p>'
    return h + ('<p>Недорогая вещь, и это как раз тот случай, когда с неё удобно '
                'начинать. Чайную посуду бьют — чаще, чем кажется, — и первую '
                'лучше брать такую, потерю которой не будете переживать.</p>')
