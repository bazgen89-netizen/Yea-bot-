    random.seed(1)
    allov = []
    for g, ids in B.groups.items():
        ids = [i for i in ids if i in out]
        if len(ids) < 3:
            continue
        pairs = [(a, b) for n, a in enumerate(ids) for b in ids[n + 1:]]
        ov = []
        for a, b in random.sample(pairs, min(80, len(pairs))):
            A, Bs = toks(out[a]), toks(out[b])
            if A and Bs:
                ov.append(len(A & Bs) / len(A | Bs) * 100)
        allov += ov
        print(f'   {g:26} {len(ids):3} шт  пересечение {statistics.median(ov):.0f}%')
    print(f'ОБЩАЯ МЕДИАНА ПЕРЕСЕЧЕНИЯ: {statistics.median(allov):.0f}%')

