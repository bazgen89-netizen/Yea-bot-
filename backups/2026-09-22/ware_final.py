def article_for(kind, mat):
    """У чайников ссылка зависит от материала: исин — своя статья."""
    if kind == 'чайник':
        if mat in ('исин', 'глина'):
            return ('Исинский чайник: как выбрать и почему он меняет вкус чая',
                    '/isinskij-chajnik/')
        return ('Чайник для заварки: какой выбрать', '/chajnik-dlya-zavarki-vybor/')
    return ARTICLE.get(kind)


