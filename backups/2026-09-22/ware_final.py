def lead2(x, kind, v, mat, mk, dec):
    """Вводный абзац сообщает то, чего нет в названии, а не пересказывает его."""
    name = B.clean_title(x['name'])
    s = f'<p><strong>{name}</strong> — '
    s += PURPOSE.get(kind, 'предмет чайного стола')
    s += '.'
    if mk:
        s += f' Производитель, указанный на карточке, — {mk}.'
    if dec:
        s += ' ' + ('Оформление: ' + ', '.join(dec) + '.')
    s += ' Купить с доставкой по России — в нашем магазине во Владимире.</p>'
    return s


def build(x):
    g = B.GROUP_OF.get(x['id'], 'прочее')
    kind = B.KIND.get(g, 'предмет')
    v = volume(x['name'])
    mat = material(x['name'])
    mk = maker(x['name'])
    dec = decor(x['name'])

    blocks = [f'<h2>🫖 {B.clean_title(x["name"])}</h2>',
              lead2(x, kind, v, mat, mk, dec),
              '<hr />',
              B.specs(x, kind, v, mat, mk, dec)]

    use = USE.get(kind)
    if use:
        blocks += ['<hr />', '<h2>Как пользоваться</h2>', f'<p>{use}</p>']

    pr = pairing(kind, v, mat)
    if pr:
        blocks += ['<hr />', pr]

    pe = peers(x, kind, v, B.VOLUMES_BY_GROUP.get(g, []))
    if pe:
        blocks += ['<hr />', pe]

    pn = price_note(kind, x.get('price'), mat, dec)
    if pn:
        blocks += ['<hr />', pn]

    if mat and CARE.get(mat):
        blocks += ['<hr />', '<h2>Уход</h2>',
                   CARE[mat].replace('<p><strong>Уход.</strong> ', '<p>')]

    q = item_faq(x, g, kind, v, mat, dec)
    if q:
        blocks += ['<hr />', '<h2>Вопросы по этой вещи</h2>']
        for a, b in q:
            blocks.append(f'<p><strong>{a}</strong><br />{b}</p>')

    art = article_for(kind, mat)
    if art:
        blocks += ['<hr />',
                   f'<p>Подробный разбор — в статье «<a href="{art[1]}">{art[0]}</a>».</p>']
    return '\n'.join(blocks)


