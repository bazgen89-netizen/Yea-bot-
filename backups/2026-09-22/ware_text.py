def volume(name):
    """Объём в миллилитрах из названия."""
    m = re.search(r'(\d{2,4})\s*мл', name, re.I)
    return int(m.group(1)) if m else None


def dims(name):
    m = re.findall(r'(\d+[.,]?\d*)\s*см', name)
    return [x.replace(',', '.') for x in m]


MATERIALS = [
    ('исин',      r'исин|цзыша|zisha'),
    ('глина',     r'глин'),
    ('фарфор',    r'фарфор'),
    ('стекло',    r'стекл'),
    ('бамбук',    r'бамбук'),
    ('дерево',    r'дерев|палисандр|полисандр|сандал'),
    ('серебро',   r'серебр'),
    ('металл',    r'металл|металич|латун|сталь'),
    ('керамика',  r'керамик|глазур'),
]


def material(name):
    n = name.lower()
    for label, pat in MATERIALS:
        if re.search(pat, n):
            return label
    return None


