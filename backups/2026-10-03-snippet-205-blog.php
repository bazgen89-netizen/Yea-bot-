/**
 * Waystea: заголовок и описание страницы «Блог».
 *
 * Было `<title>Блог - Waystea</title>` — четырнадцать символов, ни одного
 * слова, по которому человек ищет. H1 на странице нет вовсе (проверено
 * разбором живой страницы: H1 ноль, H2 два), а это сборная страница всех
 * статей, и она могла бы приводить людей по общим запросам о чае.
 *
 * Заголовок первого уровня правится в шаблоне Elementor (страница 9987),
 * здесь — только то, что видно в поиске.
 *
 * Откат: выключить сниппет, Yoast вернёт прежний заголовок.
 */
add_filter( 'wpseo_title', function ( $title ) {
	if ( is_page( 9987 ) ) {
		return 'Блог о китайском чае: как заваривать, выбирать и хранить — Waystea';
	}
	return $title;
}, 20 );

add_filter( 'wpseo_metadesc', function ( $desc ) {
	if ( is_page( 9987 ) ) {
		return 'Статьи о китайском чае: как заваривать пуэр, улун и белый чай, '
			. 'сколько граммов на чашку, как хранить дома и какую посуду выбрать. '
			. 'Пишем из чайной во Владимире.';
	}
	return $desc;
}, 20 );
