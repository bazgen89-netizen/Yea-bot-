BRANCHES: dict = {b.code: b for b in (GAGARINA, GASTROMARKET, CHERYOMUSHKI)}


def find(code: str) -> Optional[Branch]:
    return BRANCHES.get((code or "").strip().lower())


def titles() -> str:
    return ", ".join(b.title for b in BRANCHES.values())
