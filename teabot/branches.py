"""Точки Waystea: у каждой своя тематика, аудитория и тон ответов.

Один магазин — не то же самое, что другой: на Гагарина заходят туристы за
подарком, в гастромаркет приходят пить чай, в Черёмушки — покупать его
домой. Поэтому отзыв на Яндекс Картах разбирается не «от имени сети»,
а от имени конкретной точки: её профиль подмешивается в запрос к AI.

Тексты упаковки карточек (описание, рубрики, посты) — в docs/BRANCHES.md.
"""
from dataclasses import dataclass, field
from typing import Optional


@dataclass(frozen=True)
class Branch:
    """Профиль одной точки."""

    code: str            # короткий ключ: в переменных окружения и callback_data
    title: str           # как называем точку в интерфейсе бота
    format: str          # что это за место одним словосочетанием
    positioning: str     # главная мысль карточки
    audience: str        # кто сюда приходит
    focus: tuple         # что продвигаем в первую очередь
    tone: str            # как разговариваем в ответах
    avoid: str           # чего в ответах не обещаем
    keywords: tuple = field(default=())

    def reply_profile(self) -> str:
        """Блок для системного запроса к AI — чтобы ответ звучал от этой точки."""
        return (
            f"Отвечаешь от имени точки «{self.title}» ({self.format}). "
            f"Позиционирование: {self.positioning} "
            f"Кто сюда приходит: {self.audience} "
            f"В ответе уместно упомянуть: {', '.join(self.focus)}. "
            f"Тон: {self.tone} "
            f"Не упоминай: {self.avoid}"
        )


