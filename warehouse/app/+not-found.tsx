import { Redirect } from 'expo-router';

/**
 * Куда попадает любой неизвестный адрес.
 *
 * Нужен прежде всего собранной веб-версии: файл, открытый с диска, имеет адрес
 * вида `file:///…/sklad.html`, и такого маршрута в приложении, разумеется, нет —
 * без этого экрана вместо приложения показывалось «Unmatched Route».
 *
 * Заодно и в обычной жизни устаревшая ссылка приводит на Главную, а не в тупик.
 */
export default function NotFound() {
  return <Redirect href="/" />;
}
