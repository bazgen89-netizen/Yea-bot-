<?php
/**
 * Приёмник и хранилище Wayshop.
 *
 * Кладётся один раз в ту же папку, где лежит программа (`/sklad/`), и больше
 * не трогается.
 *
 * ЧТО НУЖНО СДЕЛАТЬ РУКАМИ — ОДИН РАЗ:
 *
 *   1. Придумайте длинную случайную строку — 40-50 знаков, буквы и цифры.
 *      Это ключ. Никому его не показывайте и в переписку не вставляйте.
 *   2. Впишите её ниже вместо слова ВПИШИТЕ-СЮДА-СВОЙ-КЛЮЧ.
 *   3. Положите этот файл рядом с index.html в папку /sklad/.
 *   4. Ту же строку задайте переменной окружения SITE_KEY в настройках среды
 *      сборки — там же, где лежит ключ CloudShop. Не в переписке.
 *
 * Всё. Дальше обновления идут сами.
 *
 * ПОЧЕМУ ТАК, А НЕ ПО FTP. С машины, где собирается программа, наружу открыт
 * только 443-й порт. 21-й (FTP), 990-й (FTPS) и 22-й (SFTP) закрыты наглухо —
 * проверено. Значит, единственная дорога к хостингу — обычный https, а на том
 * конце должен кто-то стоять и принимать. Это он и есть.
 *
 * ЗАЧЕМ ОН ЕЩЁ И ХРАНИЛИЩЕ. Машина, на которой всё собирается, каждую ночь
 * создаётся пустой, а выгрузка из CloudShop в git не лежит — там настоящие
 * телефоны. Раньше ночь поэтому начиналась с полного переноса 46 429 чеков:
 * полчаса работы, и если он спотыкался, не выходило уже ничего — ни сборки,
 * ни выкладки. Теперь выгрузка ночует здесь, рядом с программой и под тем же
 * паролем: ночь забирает её за секунды и дописывает только новые чеки.
 *
 * ЧЕГО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ. Он не отдаёт наружу ничего, кроме трёх заранее
 * названных файлов, и только по ключу. Ни содержимого папки, ни ошибок с
 * путями. На любой запрос без верного ключа — одинаковая пустая 404-я: со
 * стороны не отличить от несуществующей страницы, так что перебирать ключ
 * вслепую бессмысленно и незаметно нечем.
 */

const КЛЮЧ = 'ВПИШИТЕ-СЮДА-СВОЙ-КЛЮЧ';

/**
 * Что этому файлу позволено трогать — весь список, целиком.
 *
 * Именно список, а не «любое имя»: иначе ключом можно было бы положить в
 * папку свой .htaccess и снять пароль, под которым лежат 3 272 телефона.
 *
 *   index.html  — сама программа;
 *   dannye.tgz  — выгрузка из CloudShop без фотографий, около 2 МБ;
 *   foto.tgz    — фотографии товаров, около 26 МБ, меняются редко.
 */
const МОЖНО = ['index.html', 'dannye.tgz', 'foto.tgz'];

/** Больше 60 МБ принимать нечего: самое большое здесь весит 26. */
const ПРЕДЕЛ = 60 * 1024 * 1024;

function отказать() {
    http_response_code(404);
    exit;
}

function ответить(array $что) {
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode($что, JSON_UNESCAPED_UNICODE);
    exit;
}

// Ключ не заменили — значит файл положили, но не настроили. Принимать в таком
// виде нельзя: ключ по умолчанию знает каждый, кто видел этот файл.
if (КЛЮЧ === 'ВПИШИТЕ-СЮДА-СВОЙ-КЛЮЧ' || strlen(КЛЮЧ) < 20) {
    отказать();
}

$прислан = $_SERVER['HTTP_X_KLYUCH'] ?? '';
// hash_equals, а не ==: обычное сравнение обрывается на первом несовпавшем
// знаке, и по времени ответа ключ подбирается по одному знаку за раз.
if (!is_string($прислан) || !hash_equals(КЛЮЧ, $прислан)) {
    отказать();
}

$папка = __DIR__;

/** Какой из разрешённых файлов имеется в виду. По умолчанию — программа. */
$имя = $_GET['fajl'] ?? 'index.html';
if (!in_array($имя, МОЖНО, true)) {
    отказать();
}

$готовый = $папка . DIRECTORY_SEPARATOR . $имя;
// Пока едет — лежит отдельно. Готовый файл подменяется только целиком.
$черновик = $папка . DIRECTORY_SEPARATOR . '.' . $имя . '.частями';

switch ($_GET['chto'] ?? '') {

    // Начинаем заново: старый недовезённый черновик выбрасываем.
    case 'nachat':
        if (file_exists($черновик) && !unlink($черновик)) {
            ответить(['ok' => false, 'беда' => 'не стереть черновик']);
        }
        if (file_put_contents($черновик, '') === false) {
            ответить(['ok' => false, 'беда' => 'папка не пишется']);
        }
        ответить(['ok' => true]);

    // Кусок. Их много: целиком 26 МБ хостер за раз не примет.
    case 'kusok':
        if (!file_exists($черновик)) {
            ответить(['ok' => false, 'беда' => 'не начато']);
        }
        $кусок = file_get_contents('php://input');
        if ($кусок === false) {
            ответить(['ok' => false, 'беда' => 'кусок не прочитался']);
        }
        if (filesize($черновик) + strlen($кусок) > ПРЕДЕЛ) {
            ответить(['ok' => false, 'беда' => 'слишком большой файл']);
        }
        if (file_put_contents($черновик, $кусок, FILE_APPEND) === false) {
            ответить(['ok' => false, 'беда' => 'кусок не дописался']);
        }
        ответить(['ok' => true, 'сейчас' => filesize($черновик)]);

    /*
     * Готово — но только если файл доехал целиком и не побился.
     *
     * Сверяем длину и sha256. Без этой сверки оборванная посередине заливка
     * заменила бы работающую программу огрызком, и Вазген увидел бы белый
     * экран вместо склада. Подмена — через rename: она мгновенная, и в
     * промежутке не бывает мига, когда index.html наполовину старый.
     */
    case 'zakonchit':
        if (!file_exists($черновик)) {
            ответить(['ok' => false, 'беда' => 'не начато']);
        }
        $ждём_размер = (int) ($_SERVER['HTTP_X_RAZMER'] ?? 0);
        $ждём_сумму = strtolower($_SERVER['HTTP_X_SUMMA'] ?? '');
        $есть_размер = filesize($черновик);

        if ($ждём_размер !== $есть_размер) {
            ответить(['ok' => false, 'беда' => "доехало $есть_размер из $ждём_размер"]);
        }
        if ($ждём_сумму !== hash_file('sha256', $черновик)) {
            ответить(['ok' => false, 'беда' => 'файл побился в дороге']);
        }
        if (!rename($черновик, $готовый)) {
            ответить(['ok' => false, 'беда' => 'не переименовать']);
        }
        ответить(['ok' => true, 'размер' => $есть_размер]);

    /*
     * Отдать файл обратно.
     *
     * Ради этого всё и затевалось: ночь забирает отсюда вчерашнюю выгрузку
     * и дописывает к ней только новые чеки, вместо того чтобы полчаса
     * тянуть все 46 429 заново.
     *
     * readfile, а не file_get_contents: 26 МБ незачем поднимать в память
     * целиком, хостер на этом и споткнётся.
     */
    case 'vzyat':
        if (!file_exists($готовый)) {
            ответить(['ok' => false, 'беда' => 'такого файла здесь нет']);
        }
        header('Content-Type: application/octet-stream');
        header('Content-Length: ' . filesize($готовый));
        header('X-Summa: ' . hash_file('sha256', $готовый));
        readfile($готовый);
        exit;

    /*
     * Поставить пароль на папку — один раз и навсегда.
     *
     * Вазгену иначе пришлось бы класть сюда ещё два файла руками, а он
     * справедливо сказал, что «без моего участия» так не выглядит. Пусть
     * их положит тот, кто уже здесь.
     *
     * ОДИН РАЗ — И БОЛЬШЕ НИКОГДА. Если .htaccess уже лежит, отвечаем
     * отказом и ничего не трогаем. Это не придирчивость: без этого запрета
     * всякий, кто добыл ключ, снял бы им пароль с папки и прочитал бы
     * 3 272 телефона. А так ключ умеет только положить защиту, снять — не
     * умеет. Снять можно лишь из файлового менеджера хостинга, руками.
     */
    case 'zashchita':
        $htaccess = $папка . DIRECTORY_SEPARATOR . '.htaccess';
        $htpasswd = $папка . DIRECTORY_SEPARATOR . '.htpasswd';

        if (file_exists($htaccess)) {
            ответить(['ok' => false, 'беда' => 'защита уже стоит, снимать её отсюда нельзя']);
        }

        $что = json_decode(file_get_contents('php://input'), true);
        if (!is_array($что) || empty($что['htaccess']) || empty($что['htpasswd'])) {
            ответить(['ok' => false, 'беда' => 'не прислали содержимое']);
        }

        // Пароль кладётся первым: если следом не ляжет .htaccess, папка
        // останется как была. В обратном порядке .htaccess сослался бы на
        // несуществующий файл паролей, и Apache отдал бы 500 — программа
        // стала бы недоступна и Вазгену тоже.
        if (file_put_contents($htpasswd, $что['htpasswd']) === false) {
            ответить(['ok' => false, 'беда' => 'не записать .htpasswd']);
        }
        if (file_put_contents($htaccess, $что['htaccess']) === false) {
            unlink($htpasswd);
            ответить(['ok' => false, 'беда' => 'не записать .htaccess']);
        }
        ответить(['ok' => true, 'папка' => $папка]);

    // Проверка связи: ключ подошёл, что тут лежит, папка пишется.
    case 'proverka':
        $лежит = [];
        foreach (МОЖНО as $один) {
            $путь = $папка . DIRECTORY_SEPARATOR . $один;
            $лежит[$один] = file_exists($путь) ? filesize($путь) : 0;
        }
        ответить([
            'ok' => true,
            'пишется' => is_writable($папка),
            'лежит' => $лежит,
            'защита' => file_exists($папка . DIRECTORY_SEPARATOR . '.htaccess'),
            // Настоящий путь к папке. В .htaccess его надо писать точно, а
            // угаданный по имени хостинга даёт 500 — и программа перестаёт
            // открываться вообще. Пусть говорит тот, кто знает.
            'папка' => $папка,
            // Старое имя — чтобы прежняя версия выкладки не сломалась.
            'программа' => $лежит['index.html'],
        ]);
}

отказать();
