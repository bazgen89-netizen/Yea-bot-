/**
 * Догон истории: с какого дня спрашивать CloudShop и как нумеровать смены.
 *
 * Вынесено из `import-cloudshop.mjs` отдельным файлом ровно затем, чтобы это
 * можно было проверить тестами: сам перенос ходит в сеть и читает диск с
 * первой же строки, в тест его не возьмёшь. Здесь нет ни сети, ни файлов —
 * только числа и даты.
 *
 * Проверяется в `src/domain/__tests__/догонВыгрузки.test.ts`.
 *
 * Файл нарочно `.cjs`, а не `.mjs`: перенос берёт его обычным `import`
 * (Node так умеет с CommonJS), а тесты — через `require`. Будь он модулем,
 * jest не загрузил бы его без экспериментального ключа в каждом запуске.
 */

/**
 * С какого дня забирать историю, когда прежней выгрузки нет.
 *
 * Первые чеки у него — 2019 год. Дата вынесена сюда, чтобы её было видно:
 * взять «с начала времён» нельзя, окна пришлось бы гонять впустую за годы,
 * которых не было.
 */
const SINCE = '2019-01-01';

/**
 * Сколько суток перекрытия брать сверх уже собранного.
 *
 * Чек могут провести задним числом, а прошлый перенос мог оборваться на
 * середине последнего окна. Трое суток — дёшево (три-четыре запроса) и
 * закрывают оба случая; лишнее отсеется при склейке по времени и номеру.
 */
const ЗАПАС_ДНЕЙ = 3;

/**
 * Чем кончается уже собранная выгрузка.
 *
 * Берём **раннюю** из двух последних дат — по чекам и по складским
 * документам: догонять надо оттуда, где отстал хоть один из двух разделов,
 * иначе во втором останется дыра.
 *
 * Если одного из списков нет или он пуст, догонять нечего: `null`.
 *
 * @param {Array<{ at?: string | null }> | null} чеки
 * @param {Array<{ at?: string | null }> | null} документы
 * @returns {string | null}
 */
function крайВыгрузки(чеки, документы) {
  const последний = (строки) => {
    if (!Array.isArray(строки) || строки.length === 0) return null;

    let край = null;
    for (const строка of строки) {
      const день = typeof строка?.at === 'string' ? строка.at.slice(0, 10) : null;
      if (день && (край === null || день > край)) край = день;
    }
    return край;
  };

  const поЧекам = последний(чеки);
  const поДокументам = последний(документы);
  if (!поЧекам || !поДокументам) return null;
  return поЧекам < поДокументам ? поЧекам : поДокументам;
}

/**
 * С какого дня забирать историю на этот раз.
 *
 * Полный обход — это по месячному окну на каждый месяц с 2019 года, и так
 * пять раз: корректировки, чеки, возвраты продаж, закупки, возвраты
 * поставщику. Замерено: восемнадцать минут сплошных запросов к CloudShop,
 * каждую ночь, ради трёх десятков новых чеков. Догон тех же данных — тридцать
 * секунд.
 *
 * Ровно столько ночное задание и не выдерживало: у него на перенос отведено
 * двадцать пять минут, и он в них то укладывался, то нет. Вазген видел
 * последствия неделю подряд и сказал прямо — «уже неделю по ночам не
 * обновляется». Тридцать секунд в этот срок укладываются с запасом.
 *
 * Заново всю историю и не нужно: она уже лежит в файлах и только
 * дополняется — и чеки (`mergeHistory`), и документы (`mergeDocs`).
 * Достаточно взять с того дня, которым прежняя выгрузка кончается, отступив
 * на `ЗАПАС_ДНЕЙ` назад.
 *
 * Что **не** сокращается — справочник: `/product` и `/product/deleted`
 * спрашиваются целиком, по одному запросу каждый.
 *
 * @param {{ заказано?: string | null, всё?: boolean, край?: string | null }} [настройки]
 * @returns {string}
 */
function откудаИсторию({ заказано = null, всё = false, край = null } = {}) {
  if (заказано) return заказано;
  if (всё) return SINCE;
  if (!край) return SINCE;

  const назад = new Date(`${край}T00:00:00Z`);
  if (Number.isNaN(назад.getTime())) return SINCE;

  назад.setUTCDate(назад.getUTCDate() - ЗАПАС_ДНЕЙ);
  const день = назад.toISOString().slice(0, 10);
  return день < SINCE ? SINCE : день;
}

/**
 * Смена — порядковым номером, а не внутренним кодом.
 *
 * Смены в CloudShop пронумерованы подряд: в его документе от 23 августа
 * стоит «Смена #3430». Ключ отдаёт только внутренний код, поэтому нумеруем
 * сами — по времени первого чека смены, от самой старой к самой свежей.
 *
 * Считается **после** склейки и по всему списку сразу. Пока счёт шёл до неё,
 * по одной свежей порции, догоняющий перенос выдавал приехавшим сменам
 * номера с единицы — и в журнале рядом с трёхтысячной сменой вставала
 * «Смена #1». Теперь номера приехавших продолжают уже расставленные: у
 * прежних чеков в поле стоит число, у свежих — код, по этому и различаем.
 *
 * Список правится на месте; возвращается общее число смен.
 *
 * @param {Array<{ at?: string | null, sh?: string | number | null }>} чеки
 * @returns {number}
 */
function пронумероватьСмены(чеки) {
  let наибольший = 0;
  const первыйЧек = new Map();

  for (const чек of чеки) {
    if (!чек.sh) continue;
    if (typeof чек.sh === 'number') {
      if (чек.sh > наибольший) наибольший = чек.sh;
      continue;
    }
    if (!чек.at) continue;
    const было = первыйЧек.get(чек.sh);
    if (!было || чек.at < было) первыйЧек.set(чек.sh, чек.at);
  }

  const порядок = [...первыйЧек.entries()].sort((a, b) => (a[1] < b[1] ? -1 : 1));
  const номер = new Map(порядок.map(([код], место) => [код, наибольший + место + 1]));

  for (const чек of чеки) {
    if (typeof чек.sh === 'string') чек.sh = номер.get(чек.sh) ?? null;
    else if (!чек.sh) чек.sh = null;
  }

  return наибольший + номер.size;
}

module.exports = { SINCE, ЗАПАС_ДНЕЙ, крайВыгрузки, откудаИсторию, пронумероватьСмены };
