import type { SqlDriver } from './driver';
import type { Id } from '../domain/types';

/**
 * Корзина: всё, что убрали из работы, и откуда это можно вернуть.
 *
 * У Вазгена в кабинете этот раздел живой: список удалённого с датой, отбор по
 * виду и за период, кнопка «Восстановить». У нас на его месте стояла надпись
 * «Раздел в работе».
 *
 * Ничего нового в базе для этого не завелось: у товаров, контрагентов,
 * магазинов и счетов давно есть признак `archived` — удаление у нас и так
 * мягкое. Добавилась одна колонка `archived_at`, чтобы знать **когда**.
 *
 * Документов здесь нет, и это не забывчивость: отмена документа (`cancelDoc`)
 * стирает его вместе с движениями по складу насовсем — возвращать оттуда
 * нечего. Показать документ в корзине значило бы обещать кнопку, которая не
 * сработает.
 */

/** Что именно лежит в корзине. Подписи — как в боковом меню. */
export const ВИДЫ = {
  product: 'Товары и услуги',
  counterparty: 'Контрагенты',
  location: 'Магазины',
  account: 'Счета',
} as const;

export type ВидКорзины = keyof typeof ВИДЫ;

export interface СтрокаКорзины {
  вид: ВидКорзины;
  id: Id;
  name: string;
  /** Когда убрали. `null` у того, что убрали до появления колонки. */
  archived_at: string | null;
  /** Вторая строка под названием: артикул, телефон, адрес — что уместно. */
  note: string | null;
}

interface Откуда {
  вид: ВидКорзины;
  таблица: string;
  /** Чем подписать вторую строку. */
  подпись: string;
}

const ОТКУДА: Откуда[] = [
  { вид: 'product', таблица: 'products', подпись: 'sku' },
  { вид: 'counterparty', таблица: 'counterparties', подпись: 'phone' },
  { вид: 'location', таблица: 'locations', подпись: 'address' },
  { вид: 'account', таблица: 'accounts', подпись: 'type' },
];

export interface ОтборКорзины {
  /** Пусто — все виды сразу, как в его «ТИП». */
  вид?: ВидКорзины | null;
  /** Границы периода в виде `ГГГГ-ММ-ДД`; пусто — без ограничения. */
  от?: string | null;
  до?: string | null;
}

/**
 * Что лежит в корзине.
 *
 * Свежее сверху: человек приходит сюда за тем, что удалил только что, а не
 * за прошлогодним. Строки без даты — в самом конце: когда они удалены,
 * неизвестно, и ставить их вперемешку с датированными было бы враньём.
 */
export function listTrash(db: SqlDriver, отбор: ОтборКорзины = {}): СтрокаКорзины[] {
  const строки: СтрокаКорзины[] = [];

  for (const откуда of ОТКУДА) {
    if (отбор.вид && отбор.вид !== откуда.вид) continue;

    const условия: string[] = ['archived = 1'];
    const параметры: string[] = [];

    if (отбор.от) {
      условия.push('archived_at >= ?');
      параметры.push(`${отбор.от} 00:00:00`);
    }
    if (отбор.до) {
      условия.push('archived_at <= ?');
      параметры.push(`${отбор.до} 23:59:59`);
    }

    const найдено = db.all<{ id: Id; name: string; archived_at: string | null; note: string | null }>(
      `SELECT id, name, archived_at, ${откуда.подпись} AS note
         FROM ${откуда.таблица}
        WHERE ${условия.join(' AND ')}`,
      параметры,
    );

    for (const строка of найдено) {
      строки.push({ вид: откуда.вид, ...строка });
    }
  }

  return строки.sort((а, б) => {
    if (а.archived_at === б.archived_at) return а.name.localeCompare(б.name, 'ru');
    if (!а.archived_at) return 1;
    if (!б.archived_at) return -1;
    return а.archived_at < б.archived_at ? 1 : -1;
  });
}

/** Сколько всего лежит в корзине — для значка у пункта меню. */
export function countTrash(db: SqlDriver): number {
  return ОТКУДА.reduce((сумма, откуда) => {
    const строка = db.get<{ сколько: number }>(
      `SELECT COUNT(*) AS сколько FROM ${откуда.таблица} WHERE archived = 1`,
    );
    return сумма + (строка?.сколько ?? 0);
  }, 0);
}

/**
 * Вернуть из корзины.
 *
 * Возвращаем ровно то, что убирали: признак снимается, дата стирается. Если
 * такой строки нет или она и не была удалена — молчим и ничего не портим.
 */
export function restoreFromTrash(db: SqlDriver, вид: ВидКорзины, id: Id): void {
  const откуда = ОТКУДА.find((один) => один.вид === вид);
  if (!откуда) return;

  db.run(`UPDATE ${откуда.таблица} SET archived = 0, archived_at = NULL WHERE id = ?`, [id]);
}

/** Вернуть несколько разом — в его корзине строки отмечаются галочками. */
export function restoreMany(db: SqlDriver, строки: { вид: ВидКорзины; id: Id }[]): number {
  return db.tx(() => {
    for (const строка of строки) restoreFromTrash(db, строка.вид, строка.id);
    return строки.length;
  });
}
