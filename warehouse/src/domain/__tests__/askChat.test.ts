import { askSystemChat, какСказал, разобратьЧат, ЧАТ, ПРАВИЛА } from '../askPrompt';

/**
 * Разбор ответа в чате.
 *
 * Вазген попросил вместо страницы «Спросить у склада» чат: спросить у ИИ
 * можно не только про цифры, но и совета или текст для поста. Значит ответ
 * без запроса — это не отказ, а ответ, и его нельзя ни обрезать, ни принять
 * за сломанный запрос.
 */
describe('разбор ответа в чате', () => {
  it('ответ с запросом — как и раньше: слова и запрос', () => {
    const ответ = разобратьЧат('Смотрю продажи за август.\n\n```sql\nSELECT 1\n```');
    expect(ответ).toEqual({ sql: 'SELECT 1', comment: 'Смотрю продажи за август.' });
  });

  it('совет без запроса — это ответ, а не отказ, и он целиком', () => {
    const совет = 'Поднимите цену на пуэр на 10 %. '.repeat(40);
    const ответ = разобратьЧат(совет);
    expect(ответ.sql).toBe('');
    // Раньше обрезалось до пятисот знаков — для совета это полуслово.
    expect(ответ.comment).toBe(совет.trim());
  });

  it('английское select или with в тексте — не запрос', () => {
    // Так и было бы с прежним разбором: он искал SELECT где попало, и совет
    // превращался в сломанный запрос к базе.
    const текст = 'Можно сделать акцию with подарком: select три чая и получить четвёртый.';
    expect(разобратьЧат(текст)).toEqual({ sql: '', comment: текст });
  });

  it('голый запрос без блока — всё равно запрос', () => {
    expect(разобратьЧат('SELECT 2 AS n').sql).toBe('SELECT 2 AS n');
  });

  it('«НЕЛЬЗЯ:» в начале показывается без служебного слова', () => {
    expect(разобратьЧат('НЕЛЬЗЯ: в базе нет погоды.').comment).toBe('в базе нет погоды.');
  });

  it('обычное слово «нельзя» в середине совета — не отказ', () => {
    const текст = 'Скидку больше 30 % давать нельзя: уйдёте в минус.';
    expect(разобратьЧат(текст).comment).toBe(текст);
  });
});

describe('правила чата', () => {
  it('основные правила остаются как были — они сверяются с сервером', () => {
    // Чатовая добавка не правит ПРАВИЛА, а приклеивается после них.
    expect(askSystemChat('таблицы')).toContain(ПРАВИЛА);
    expect(askSystemChat('таблицы')).toContain(ЧАТ);
    expect(ПРАВИЛА).not.toContain('Это разговор');
  });

  it('ответ помощника в памяти звучит так, как он его дал', () => {
    expect(какСказал('Считаю выручку.', 'SELECT 1')).toBe('Считаю выручку.\n\n```sql\nSELECT 1\n```');
    expect(какСказал('Просто совет.', '')).toBe('Просто совет.');
  });
});
