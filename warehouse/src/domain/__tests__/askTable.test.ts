import {
  isCountedColumn,
  isMoneyColumn,
  отобрать,
  самСтолбец,
  суммы,
  упорядочить,
} from '../askTable';

/**
 * Таблица ответа помощника: порядок, отбор, итоги.
 *
 * Он попросил считать «от большего к меньшему» и спросил, не нужен ли фильтр.
 * Нужен — и стоить он не должен ничего: строки уже посчитаны и лежат в
 * памяти, а переспрашивать модель ради другого порядка значило бы платить за
 * то, что и так есть.
 */
describe('таблица ответа', () => {
  const columns = ['Товар', 'Ед.', 'Продано', 'Выручка, ₽'];
  const rows: unknown[][] = [
    ['Шу Пуэр 9978', 'шт', 47, 17_036],
    ['Шэн Пуэр Булан', 'гр', 670.6, 10_059],
    ['Габа Алишань', 'гр', 528.4, 10_039.6],
    ['Те Гуань Инь', 'шт', 2, 10_200],
  ];

  describe('порядок', () => {
    it('по умолчанию берётся столбец с деньгами — он последний числовой', () => {
      expect(самСтолбец(rows, columns)).toBe(3);
    });

    it('от большего к меньшему — самое дорогое сверху', () => {
      const по = упорядочить(rows, 3, true);
      expect(по.map((row) => row[0])).toEqual([
        'Шу Пуэр 9978',
        'Те Гуань Инь',
        'Шэн Пуэр Булан',
        'Габа Алишань',
      ]);
    });

    it('и наоборот, если нажали второй раз', () => {
      expect(упорядочить(rows, 3, false)[0][0]).toBe('Габа Алишань');
    });

    /** Иначе «Я» окажется раньше «а»: сравнение по кодам букв — не порядок. */
    it('слова по-русски, а не по кодам букв', () => {
      const слова: unknown[][] = [['яблоко'], ['Абрикос'], ['банан']];
      expect(упорядочить(слова, 0, false).map((row) => row[0])).toEqual([
        'Абрикос',
        'банан',
        'яблоко',
      ]);
    });

    /** Пустота — это не «самое маленькое», её просто нет. Место ей в конце. */
    it('пустые ячейки всегда внизу, при любом порядке', () => {
      const сПустыми: unknown[][] = [['а', 5], ['б', null], ['в', 1]];
      expect(упорядочить(сПустыми, 1, true).map((row) => row[0])).toEqual(['а', 'в', 'б']);
      expect(упорядочить(сПустыми, 1, false).map((row) => row[0])).toEqual(['в', 'а', 'б']);
    });

    it('исходные строки не трогает — их ещё показывать', () => {
      const было = [...rows];
      упорядочить(rows, 2, true);
      expect(rows).toEqual(было);
    });
  });

  describe('отбор', () => {
    it('оставляет строки со словом в любой ячейке', () => {
      expect(отобрать(rows, 'пуэр')).toHaveLength(2);
    });

    it('заглавные буквы не мешают — в отличие от SQLite', () => {
      expect(отобрать(rows, 'ПУЭР')).toHaveLength(2);
      expect(отобрать(rows, 'Шу')).toHaveLength(1);
    });

    it('пустой отбор оставляет всё', () => {
      expect(отобрать(rows, '   ')).toHaveLength(4);
    });
  });

  describe('итоги', () => {
    it('складывают числовые столбцы и молчат про словесные', () => {
      const итог = суммы(rows, columns);
      expect(итог[0]).toBeNull();
      expect(итог[1]).toBeNull();
      expect(итог[2]).toBeCloseTo(1248, 1);
      expect(итог[3]).toBeCloseTo(47_334.6, 1);
    });

    /**
     * Итог должен сходиться с тем, что под ним. Отобрал половину — итог по
     * половине, иначе цифра сверху противоречит таблице снизу.
     */
    it('считаются по отобранным строкам, а не по всем', () => {
      const итог = суммы(отобрать(rows, 'пуэр'), columns);
      expect(итог[3]).toBeCloseTo(27_095, 1);
    });

    /** Сумма годов и номеров чеков — число, но бессмысленное. */
    it('год и номер не складывают', () => {
      expect(суммы([[2026, 5]], ['Год', 'Продано'])).toEqual([null, 5]);
      expect(isCountedColumn('Номер чека')).toBe(false);
      expect(isCountedColumn('Продано')).toBe(true);
    });
  });

  describe('деньги узнаются по названию столбца', () => {
    it('находит их', () => {
      for (const name of ['Выручка, ₽', 'Сумма', 'Прибыль', 'Себестоимость', 'Цена']) {
        expect(isMoneyColumn(name)).toBe(true);
      }
    });

    it('и не путает с количеством', () => {
      for (const name of ['Продано', 'Остаток', 'Товар', 'Ед.']) {
        expect(isMoneyColumn(name)).toBe(false);
      }
    });
  });
});
