import { scaleFor, подРукой } from '../chart';

/**
 * Ось графика подписана круглыми числами.
 *
 * На его снимке при вершине 46 501 ось размечена нулём, десятками тысяч и
 * шестьюдесятью тысячами сверху. Если просто поделить вершину на пять,
 * подписи выйдут вида «9 300» — таких у него нет, и сравнивать два графика
 * глазами становится нельзя.
 */
describe('разметка оси графика', () => {
  it('вершина 46 501 даёт ось до 60 000 с шагом 10 000 — как у него', () => {
    const { top, ticks } = scaleFor(4_650_142);

    expect(top).toBe(6_000_000);
    expect(ticks.map((tick) => tick / 100)).toEqual([60_000, 50_000, 40_000, 30_000, 20_000, 10_000, 0]);
  });

  it('подписи идут сверху вниз и кончаются нулём', () => {
    const { ticks } = scaleFor(123_456);

    expect(ticks[ticks.length - 1]).toBe(0);
    expect(ticks[0]).toBeGreaterThan(123_456);
    for (let i = 1; i < ticks.length; i++) expect(ticks[i]).toBeLessThan(ticks[i - 1]);
  });

  it('вершина всегда выше самого высокого дня: столбик не упирается в потолок', () => {
    for (const peak of [1, 999, 100_000, 4_650_142, 98_765_432]) {
      expect(scaleFor(peak).top).toBeGreaterThan(peak);
    }
  });

  it('шаг круглый на любом порядке', () => {
    for (const peak of [500, 7_000, 250_000, 3_000_000, 41_000_000]) {
      const { ticks } = scaleFor(peak);
      const step = ticks[0] - ticks[1];
      const rubles = step / 100;
      const power = 10 ** Math.floor(Math.log10(rubles));

      expect([1, 2, 2.5, 5, 10]).toContain(Number((rubles / power).toFixed(1)));
    }
  });
});

/**
 * Плашка-линейка под курсором.
 *
 * Вазген прислал запись экрана: он водит мышью по графику, и слева на оси
 * висит число — сколько было бы на этой высоте. Оно меняется, пока мышь идёт
 * вверх-вниз над одним и тем же днём, то есть считается от высоты, а не от
 * выручки дня. У нас этого не было вовсе.
 */
describe('линейка под курсором', () => {
  const вершина = 6_000_000; // 60 000 ₽ — как на его записи
  const высота = 460;

  it('на верхней линии — вершина оси, на нижней — ноль', () => {
    expect(подРукой(вершина, 0, высота)).toBe('60,000.00');
    expect(подРукой(вершина, высота, высота)).toBe('0.00');
  });

  it('посередине — половина вершины', () => {
    expect(подРукой(вершина, высота / 2, высота)).toBe('30,000.00');
  });

  it('вид числа — его же: тысячи запятой, копейки точкой', () => {
    // 32 767,76 ₽ — ровно то, что видно у него в плашке на записи.
    const y = высота * (1 - 3_276_776 / вершина);
    expect(подРукой(вершина, y, высота)).toBe('32,767.76');
  });

  it('за края графика не выходит', () => {
    // Мышь попадает и выше верхней линии, и ниже нулевой: без ограничения
    // плашка показала бы больше вершины или отрицательную выручку.
    expect(подРукой(вершина, -30, высота)).toBe('60,000.00');
    expect(подРукой(вершина, высота + 30, высота)).toBe('0.00');
  });

  it('нулевая высота ничего не ломает', () => {
    expect(подРукой(вершина, 0, 0)).toBe('0.00');
  });
});
