import { итогДвижения } from '../money';

describe('итог движения денег', () => {
  it('складывает приход и расход отдельно и считает разницу', () => {
    expect(
      итогДвижения([
        { income: 563_350, expense: 0 },
        { income: 252_000, expense: 0 },
        { income: 0, expense: 100_000 },
      ]),
    ).toEqual({ приход: 815_350, расход: 100_000, разница: 715_350 });
  });

  it('пустой период — нули, а не NaN', () => {
    expect(итогДвижения([])).toEqual({ приход: 0, расход: 0, разница: 0 });
  });
});
