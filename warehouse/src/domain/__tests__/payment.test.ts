import { change, enough } from '../payment';
import { cashOptions } from '../payment';

/** Подсказки удобнее читать рублями — так же, как они выглядят на кнопках. */
const rubles = (total: number) => cashOptions(total * 100).map((value) => value / 100);

describe('варианты оплаты наличными', () => {
  it('первой стоит сама сумма', () => {
    expect(rubles(330)[0]).toBe(330);
    expect(rubles(1300)[0]).toBe(1300);
  });

  it('на мелком чеке третью ступень круга пропускает', () => {
    // 33 рубля: 35 и 50 — а 40, 100, 1000 и 10000 их правило выбрасывает,
    // потому что чек меньше ста. Сорок рублей никто не протягивает.
    expect(rubles(33)).toEqual([33, 35, 50, 200, 500, 2000, 5000]);
  });

  it('на чеке от ста рублей ступени остаются все', () => {
    expect(rubles(133)).toEqual([133, 135, 140, 150, 200, 500, 1000, 2000, 5000, 10000]);
  });

  it('идёт по возрастанию и без повторов', () => {
    const list = rubles(1287);
    expect([...list].sort((a, b) => a - b)).toEqual(list);
    expect(new Set(list).size).toBe(list.length);
  });

  it('круглую сумму не раздувает лишними ступенями', () => {
    // 1000 ровно: три круга из четырёх урезаются в саму сумму и пропускаются,
    // остаётся только последний.
    expect(rubles(1000)).toEqual([1000, 2000, 5000, 10000]);
  });

  it('копейки округляет вверх до рубля', () => {
    expect(rubles(12.34)).toEqual([13, 15, 20, 50, 200, 500, 2000, 5000]);
  });

  it('нулевой чек оставляет хотя бы одну кнопку', () => {
    expect(rubles(0)).toEqual([0, 1]);
  });
});

describe('сдача', () => {
  it('разница между внесённым и чеком', () => {
    expect(change(50000, 33000)).toBe(17000);
  });

  it('недоплата сдачи не даёт', () => {
    expect(change(20000, 33000)).toBe(0);
    expect(enough(20000, 33000)).toBe(false);
    expect(enough(33000, 33000)).toBe(true);
  });
});
