import { formatQty, formatQtyTotal, parseQty } from '../qty';

/**
 * Большое количество для показа.
 *
 * Вазген прислал «Оценку склада»: у него «-912 678,72 ед.», а у нас
 * стояло «-907076,82» — без единого пробела. Читать такое невозможно, и
 * это тот самый разнобой, на который он и указал: деньги разделены, а
 * количества нет.
 */
describe('количество для итогов', () => {
  const NBSP = ' ';

  it('разделяет тысячи, как у денег', () => {
    expect(formatQtyTotal(-907_076_820)).toBe(`-907${NBSP}076,82`);
    expect(formatQtyTotal(1_181_750_500)).toBe(`1${NBSP}181${NBSP}750,50`);
  });

  it('хвост всегда из двух знаков', () => {
    expect(formatQtyTotal(2_000)).toBe('2,00');
    expect(formatQtyTotal(1_500)).toBe('1,50');
    expect(formatQtyTotal(50)).toBe('0,05');
  });

  it('третий знак округляется, а не отбрасывается', () => {
    expect(formatQtyTotal(1_456)).toBe('1,46');
    expect(formatQtyTotal(1_454)).toBe('1,45');
  });

  it('ноль — ноль, а не пустая строка', () => {
    expect(formatQtyTotal(0)).toBe('0,00');
  });
});

/**
 * Формат для полей ввода остался прежним.
 *
 * `formatQty` подставляется в приход, в инвентаризацию и в строку чека —
 * то есть в то, что человек правит руками. Разделитель тысяч там пришлось
 * бы стирать при каждом изменении количества, поэтому итоговый формат
 * сделан отдельной функцией, а не заменой этой.
 */
describe('количество для ввода', () => {
  it('без разделителя тысяч', () => {
    expect(formatQty(1_181_750_500)).toBe('1181750,5');
  });

  it('хвостовые нули отбрасываются: «2», а не «2,000»', () => {
    expect(formatQty(2_000)).toBe('2');
    expect(formatQty(1_500)).toBe('1,5');
    expect(formatQty(50)).toBe('0,05');
  });

  it('читается обратно тем же разбором', () => {
    for (const число of [2_000, 1_500, 50, 1_181_750_500, -907_076_820]) {
      expect(parseQty(formatQty(число))).toBe(число);
    }
  });
});
