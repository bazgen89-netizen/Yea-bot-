import {
  дниПериода,
  подписьДня,
  подписьПериода,
  рублиИкопейки,
  поРусски,
  ячейкаОтчёта,
  естьОтбор,
  ПУСТОЙ_ОТБОР,
} from '../reportFilter';

/**
 * Отбор в отчёте на телефоне.
 *
 * Вазген прислал снимок «Продажи по дням»: сверху фишки «Дата 1 - 30 сент.»
 * и «Параметр Выручка», внизу «Итог (30 позиций)». Тридцать — это все дни
 * сентября, включая те, когда не торговали, и даже ещё не наступившие.
 */
describe('дни периода', () => {
  // Нижний Новгород: +3 часа. Так же считает и запрос.
  const МСК = 180;

  it('перечисляет все дни месяца, а не только те, где были чеки', () => {
    const дни = дниПериода('2026-08-31T21:00:00.000Z', '2026-09-30T20:59:59.999Z', МСК);

    expect(дни).toHaveLength(30);
    expect(дни[0]).toBe('2026-09-01');
    expect(дни[29]).toBe('2026-09-30');
  });

  it('день, начавшийся по Гринвичу вчера, попадает в свои сутки', () => {
    // Полночь в Нижнем — это 21:00 предыдущего дня по Гринвичу. Если сдвиг
    // не учесть, первым днём сентября окажется 31 августа.
    const дни = дниПериода('2026-08-31T21:00:00.000Z', '2026-08-31T21:30:00.000Z', МСК);
    expect(дни).toEqual(['2026-09-01']);
  });

  it('за один день — одна строка', () => {
    expect(дниПериода('2026-09-10T21:00:00.000Z', '2026-09-11T20:59:00.000Z', МСК)).toEqual([
      '2026-09-11',
    ]);
  });

  it('переход через границу месяца не теряет и не задваивает дни', () => {
    const дни = дниПериода('2026-08-29T21:00:00.000Z', '2026-09-02T20:59:59.999Z', МСК);
    expect(дни).toEqual(['2026-08-30', '2026-08-31', '2026-09-01', '2026-09-02']);
  });

  it('перевёрнутый период — пусто, а не бесконечный список', () => {
    expect(дниПериода('2026-09-30T00:00:00.000Z', '2026-09-01T00:00:00.000Z', МСК)).toEqual([]);
  });

  it('високосный февраль — двадцать девять дней', () => {
    const дни = дниПериода('2024-01-31T21:00:00.000Z', '2024-02-29T20:59:59.999Z', МСК);
    expect(дни).toHaveLength(29);
    expect(дни[28]).toBe('2024-02-29');
  });
});

describe('подпись периода на фишке', () => {
  const МСК = 180;

  it('месяц не повторяется дважды: «1 – 30 сент.»', () => {
    expect(подписьПериода('2026-08-31T21:00:00.000Z', '2026-09-30T20:59:59.999Z', МСК)).toBe(
      '1 – 30 сент.',
    );
  });

  it('через границу месяца месяц назван у обоих чисел', () => {
    expect(подписьПериода('2026-08-27T21:00:00.000Z', '2026-09-02T20:59:59.999Z', МСК)).toBe(
      '28 авг. – 2 сент.',
    );
  });

  it('один день — без тире', () => {
    expect(подписьПериода('2026-09-10T21:00:00.000Z', '2026-09-11T20:00:00.000Z', МСК)).toBe(
      '11 сент.',
    );
  });

  it('целый год подписан годом, а не «1 янв. – 31 дек.»', () => {
    expect(подписьПериода('2025-12-31T21:00:00.000Z', '2026-12-31T20:59:59.999Z', МСК)).toBe(
      '2026 год',
    );
  });

  it('через границу года назван и год', () => {
    expect(подписьПериода('2025-12-29T21:00:00.000Z', '2026-01-02T20:59:59.999Z', МСК)).toBe(
      '30 дек. 2025 – 2 янв. 2026',
    );
  });
});

describe('подпись дня в строке отчёта', () => {
  it('«30 сентября», как у него, а не «30.09»', () => {
    expect(подписьДня('2026-09-30')).toBe('30 сентября');
    expect(подписьДня('2026-01-01')).toBe('1 января');
    expect(подписьДня('2026-05-09')).toBe('9 мая');
  });
});

describe('рубли и копейки врозь', () => {
  it('отделяет копейки — их он набирает мельче', () => {
    expect(рублиИкопейки('121 076,51')).toEqual(['121 076', ',51']);
  });

  it('целая сумма остаётся целой', () => {
    expect(рублиИкопейки('0')).toEqual(['0', '']);
  });

  it('разделитель тысяч не путается с запятой копеек', () => {
    // Если бы искали первую запятую, а не последнюю, «1,234,56» разошлось
    // бы как «1» и «,234,56».
    expect(рублиИкопейки('1,234,56')).toEqual(['1,234', ',56']);
  });
});

describe('пустой отбор', () => {
  it('пока ничего не выбрано, чистить нечего', () => {
    expect(естьОтбор(ПУСТОЙ_ОТБОР)).toBe(false);
    expect(естьОтбор({ место: 2, сотрудник: null, клиент: null })).toBe(true);
    expect(естьОтбор({ место: null, сотрудник: 7, клиент: null })).toBe(true);
    expect(естьОтбор({ место: null, сотрудник: null, клиент: 42 })).toBe(true);
  });
});

describe('кабинетное число в телефонное', () => {
  const NBSP = ' ';

  it('запятые тысяч становятся пробелами, точка — запятой', () => {
    expect(поРусски('26,525.60')).toBe(`26${NBSP}525,60`);
    expect(поРусски('121,076.51')).toBe(`121${NBSP}076,51`);
    expect(поРусски('0.00')).toBe('0,00');
  });

  it('миллионы разделены во всех разрядах', () => {
    expect(поРусски('4,274,594.30')).toBe(`4${NBSP}274${NBSP}594,30`);
  });

  it('минус остаётся на месте', () => {
    expect(поРусски('-1,234.50')).toBe(`-1${NBSP}234,50`);
  });

  it('проценты и счётчики не трогаются лишнего', () => {
    expect(поРусски('894%')).toBe('894%');
    expect(поРусски('12')).toBe('12');
  });

  it('название товара с запятой не превращается в число', () => {
    // Иначе «Габа Алишань, 100 гр» стало бы «Габа Алишань 100 гр».
    expect(поРусски('Габа Алишань, 100 гр')).toBe('Габа Алишань, 100 гр');
    expect(поРусски('1 сентября')).toBe('1 сентября');
    expect(поРусски('ИТОГ')).toBe('ИТОГ');
  });
});

describe('ячейка отчёта', () => {
  const NBSP = '\u00A0';

  it('круглая сумма — без копеек, как у него «550» и «75»', () => {
    expect(ячейкаОтчёта('550.00')).toEqual(['550', '']);
    expect(ячейкаОтчёта('75.00')).toEqual(['75', '']);
  });

  it('копейки, которых не ноль, остаются — включая «,20»', () => {
    // Отбрасываются не нули вообще, а ровно нулевая дробь: «479,20» свой
    // ноль сохраняет.
    expect(ячейкаОтчёта('479.20')).toEqual(['479', ',20']);
    expect(ячейкаОтчёта('785.52')).toEqual(['785', ',52']);
    expect(ячейкаОтчёта('141.07')).toEqual(['141', ',07']);
  });

  it('тысячи разделены неразрывным пробелом', () => {
    expect(ячейкаОтчёта('6,643.05')).toEqual([`6${NBSP}643`, ',05']);
  });

  it('ноль — просто ноль', () => {
    expect(ячейкаОтчёта('0.00')).toEqual(['0', '']);
  });

  it('не-числа проходят целиком', () => {
    expect(ячейкаОтчёта('894%')).toEqual(['894%', '']);
    expect(ячейкаОтчёта('ГАБА Алишань Extra')).toEqual(['ГАБА Алишань Extra', '']);
  });
});
