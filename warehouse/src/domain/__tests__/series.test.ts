import { densify } from '../series';

/**
 * День без продаж не должен утаскивать график влево.
 *
 * Отчёт группирует продажи по дню и пустые дни просто не возвращает. График
 * же рисует точки подряд: если шестого не торговали, седьмое встаёт на место
 * шестого, и вершина оказывается не в том дне, а подпись под ней — чужая.
 * Он читает по этому графику выручку конкретного дня, так что сдвиг — это
 * не «косметика», а неверное число.
 */
describe('ряд для графика', () => {
  const august = new Date(2026, 7, 1).toISOString();

  it('раскладывает точки по номерам дней, пустые дни — нули', () => {
    const row = densify(
      [
        { day: '2026-08-01', value: 100 },
        { day: '2026-08-03', value: 300 },
        { day: '2026-08-05', value: 500 },
      ],
      august,
      7,
    );

    expect(row).toEqual([100, 0, 300, 0, 500, 0, 0]);
  });

  it('день из другого месяца в ряд не попадает', () => {
    const row = densify(
      [
        { day: '2026-07-31', value: 999 },
        { day: '2026-08-02', value: 200 },
        { day: '2026-09-01', value: 999 },
      ],
      august,
      31,
    );

    expect(row[1]).toBe(200);
    expect(row.filter((value) => value === 999)).toHaveLength(0);
  });

  it('пустой отчёт даёт ряд нулей нужной длины', () => {
    expect(densify([], august, 5)).toEqual([0, 0, 0, 0, 0]);
  });

  it('вершина остаётся в своём дне', () => {
    // 15 августа — то самое число, которое он показал на снимке: 32 125.
    const row = densify([{ day: '2026-08-15', value: 3_212_541 }], august, 31);

    expect(row[14]).toBe(3_212_541);
    expect(row.indexOf(3_212_541)).toBe(14);
  });
});
