import { weekEndingAt } from '../calendar';

/**
 * Неделя, которой открывается журнал.
 *
 * Вазген спросил: «а где всё движение товаров? куда делось?» — и был прав.
 * Журнал брал календарную неделю «в которой мы сейчас», перенесённая
 * история кончалась двадцатым августа, а на дворе стояло двадцать
 * четвёртое: отбор выходил «24 авг — 30 авг», и список — пустой.
 *
 * Ошибка тут в одни сутки, и глазами она не видна: неделя как неделя,
 * просто не та. Поэтому арифметика вынесена из экрана и проверяется здесь.
 */
describe('неделя журнала', () => {
  it('кончается последним днём с документами, а не сегодняшним', () => {
    // Сегодня 24-е, а последний документ — двадцатого.
    expect(weekEndingAt('2026-08-20', new Date('2026-08-24T09:00:00'))).toEqual({
      from: '2026-08-14',
      to: '2026-08-20',
    });
  });

  it('это ровно семь дней, считая оба края', () => {
    const { from, to } = weekEndingAt('2026-08-20');
    const days = (new Date(`${to}T12:00:00`).getTime() - new Date(`${from}T12:00:00`).getTime())
      / 86_400_000;

    expect(days).toBe(6);
  });

  it('переходит через начало месяца', () => {
    expect(weekEndingAt('2026-09-03').from).toBe('2026-08-28');
  });

  it('переходит через новый год', () => {
    expect(weekEndingAt('2026-01-02')).toEqual({ from: '2025-12-27', to: '2026-01-02' });
  });

  it('день читается по местному времени, а не по Гринвичу', () => {
    // Полночь по Гринвичу в поясе западнее — это ещё вчера. Если бы день
    // разбирался как `2026-08-20T00:00:00Z`, неделя уехала бы на сутки.
    expect(weekEndingAt('2026-08-20').to).toBe('2026-08-20');
  });

  it('пустая база — неделя от сегодняшнего дня', () => {
    expect(weekEndingAt(null, new Date('2026-08-24T09:00:00'))).toEqual({
      from: '2026-08-18',
      to: '2026-08-24',
    });
  });
});
