import { полосыГрадиента } from '../градиент';

/**
 * Градиент шапки полосами.
 *
 * Раньше восемь цветов шапки лежали в коде готовыми — посчитанными руками
 * для прежнего кабинета. Когда появился второй кабинет со своим градиентом,
 * их пришлось считать. Первый и главный тест: формула даёт **ровно те же**
 * восемь значений, что стояли руками. Иначе замена формулой была бы тихой
 * перекраской шапки, которую никто не просил.
 */
describe('полосы шапки прежнего кабинета', () => {
  // `linear-gradient(310deg, #01579b, #0288d1)` — светлое слева, поэтому
  // счёт идёт от светлого к тёмному.
  const было = [
    '#0285CE',
    '#027FC7',
    '#0279C0',
    '#0273B9',
    '#016CB3',
    '#0166AC',
    '#0160A5',
    '#015A9E',
  ];

  it('сходятся до знака с теми, что стояли руками', () => {
    expect(полосыГрадиента('#0288D1', '#01579B', 8)).toEqual(было);
  });
});

describe('полосы шапки нового кабинета', () => {
  it('считаются из его пары цветов', () => {
    // Замерено у них: linear-gradient(310deg, rgb(30,64,175), rgb(37,99,235)).
    const полосы = полосыГрадиента('#2563EB', '#1E40AF', 8);

    expect(полосы).toHaveLength(8);
    // Крайние — внутри отрезка, а не на его концах: цвет берётся из середины
    // полосы, иначе весь переход уезжает на полполосы.
    expect(полосы[0]).toBe('#2561E7');
    expect(полосы[7]).toBe('#1E42B3');
  });
});

describe('края и ошибки', () => {
  it('одна полоса — середина между цветами', () => {
    expect(полосыГрадиента('#000000', '#FFFFFF', 1)).toEqual(['#808080']);
  });

  it('от цвета к нему же — все полосы одинаковые', () => {
    expect(полосыГрадиента('#2185D0', '#2185D0', 3)).toEqual(['#2185D0', '#2185D0', '#2185D0']);
  });

  it('строчные и без решётки тоже читаются', () => {
    expect(полосыГрадиента('2185d0', '#2185D0', 1)).toEqual(['#2185D0']);
  });

  it('не цвет — исключение, а не тихий чёрный', () => {
    // Тихий чёрный означал бы чёрную шапку в собранном приложении, и искать
    // причину пришлось бы по всему коду.
    expect(() => полосыГрадиента('синий', '#2185D0')).toThrow(/не шестизначный/);
    expect(() => полосыГрадиента('#2185D', '#2185D0')).toThrow(/не шестизначный/);
  });

  it('бессмысленное число полос — тоже исключение', () => {
    expect(() => полосыГрадиента('#000000', '#FFFFFF', 0)).toThrow(/хотя бы одна/);
    expect(() => полосыГрадиента('#000000', '#FFFFFF', 2.5)).toThrow(/целое/);
  });
});
