/**
 * Догон истории из CloudShop.
 *
 * Вазген неделю подряд видел на сайте вчерашнюю программу и сказал прямо:
 * «уже неделю по ночам не обновляется». Перенос каждую ночь заново обходил
 * всю историю с 2019 года — по месячному окну на каждый месяц, и так пять
 * раз (корректировки, чеки, возвраты продаж, закупки, возвраты поставщику).
 * Замерено: восемнадцать минут против отведённых ночному заданию двадцати
 * пяти — то укладывалось, то нет, а не уложившись, задание собирало из
 * вчерашних данных. Догон тех же данных занимает тридцать секунд.
 *
 * Теперь история догоняется с того дня, которым кончается прежняя выгрузка.
 * Здесь проверено, что дата считается правильно и что смены при этом не
 * получают номера заново.
 */

// Через `require`, а не `import`: файл с логикой — CommonJS ровно затем,
// чтобы попасть сюда без экспериментальных ключей у jest. Перенос берёт тот
// же файл обычным `import` — Node так умеет.
// eslint-disable-next-line @typescript-eslint/no-var-requires
const догон = require('../../../scripts/догон.cjs') as typeof import('../../../scripts/догон.cjs');

describe('край прежней выгрузки', () => {
  it('берёт раннюю из двух последних дат', () => {
    // Чеки доехали до 10-го, документы только до 8-го: догонять надо с 8-го,
    // иначе в документах останется дыра в двое суток.
    const край = догон.крайВыгрузки(
      [{ at: '2026-09-09T10:00:00Z' }, { at: '2026-09-10T18:30:00Z' }],
      [{ at: '2026-09-08T12:00:00Z' }],
    );

    expect(край).toBe('2026-09-08');
  });

  it('пустой или отсутствующий список — догонять нечего', () => {
    expect(догон.крайВыгрузки([{ at: '2026-09-10T00:00:00Z' }], [])).toBeNull();
    expect(догон.крайВыгрузки(null, null)).toBeNull();
    expect(догон.крайВыгрузки([{}], [{ at: '2026-09-10T00:00:00Z' }])).toBeNull();
  });
});

describe('с какого дня спрашивать', () => {
  it('отступает трое суток от края', () => {
    expect(догон.откудаИсторию({ край: '2026-09-10' })).toBe('2026-09-07');
  });

  it('шагает через начало месяца, а не отнимает три от числа', () => {
    expect(догон.откудаИсторию({ край: '2026-09-01' })).toBe('2026-08-29');
    expect(догон.откудаИсторию({ край: '2026-03-02' })).toBe('2026-02-27');
  });

  it('без края — вся история, как в первый раз', () => {
    expect(догон.откудаИсторию({ край: null })).toBe(догон.SINCE);
    expect(догон.откудаИсторию()).toBe(догон.SINCE);
  });

  it('--full важнее края', () => {
    expect(догон.откудаИсторию({ край: '2026-09-10', всё: true })).toBe(догон.SINCE);
  });

  it('--since важнее всего', () => {
    expect(догон.откудаИсторию({ заказано: '2026-01-01', край: '2026-09-10', всё: true })).toBe(
      '2026-01-01',
    );
  });

  it('раньше 2019-го не уходит', () => {
    expect(догон.откудаИсторию({ край: '2019-01-02' })).toBe(догон.SINCE);
  });
});

describe('номера смен', () => {
  it('первый перенос: нумерует с единицы по времени первого чека', () => {
    const чеки = [
      { at: '2026-09-01T09:00:00Z', sh: 'позже' },
      { at: '2026-08-01T09:00:00Z', sh: 'раньше' },
      { at: '2026-08-01T19:00:00Z', sh: 'раньше' },
    ];

    expect(догон.пронумероватьСмены(чеки)).toBe(2);
    expect(чеки.map((чек) => чек.sh)).toEqual([2, 1, 1]);
  });

  it('догон: приехавшие смены продолжают уже расставленные номера', () => {
    // Вот ради чего всё: прежде счёт шёл по одной свежей порции, и рядом с
    // «Сменой #3497» в журнале вставала «Смена #1».
    const чеки = [
      { at: '2026-09-08T10:00:00Z', sh: 3496 },
      { at: '2026-09-09T10:00:00Z', sh: 3497 },
      { at: '2026-09-10T10:00:00Z', sh: 'свежая-A' },
      { at: '2026-09-11T10:00:00Z', sh: 'свежая-Б' },
      { at: '2026-09-11T15:00:00Z', sh: 'свежая-Б' },
    ];

    expect(догон.пронумероватьСмены(чеки)).toBe(3499);
    expect(чеки.map((чек) => чек.sh)).toEqual([3496, 3497, 3498, 3499, 3499]);
  });

  it('чек без смены остаётся без смены, а не получает чужой номер', () => {
    const чеки = [
      { at: '2026-09-10T10:00:00Z', sh: null },
      { at: '2026-09-10T11:00:00Z', sh: 'есть' },
      { at: '2026-09-10T12:00:00Z' },
    ];

    догон.пронумероватьСмены(чеки);
    expect(чеки.map((чек) => чек.sh)).toEqual([null, 1, null]);
  });

  it('повторный счёт по уже пронумерованному списку ничего не меняет', () => {
    // Ночное задание запускается каждую ночь; числа не должны ползти.
    const чеки = [
      { at: '2026-09-10T10:00:00Z', sh: 'A' },
      { at: '2026-09-11T10:00:00Z', sh: 'Б' },
    ];

    догон.пронумероватьСмены(чеки);
    const было = чеки.map((чек) => чек.sh);

    expect(догон.пронумероватьСмены(чеки)).toBe(2);
    expect(чеки.map((чек) => чек.sh)).toEqual(было);
  });
});
