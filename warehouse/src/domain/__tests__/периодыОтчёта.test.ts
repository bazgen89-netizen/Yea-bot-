import {
  быстрыеПериоды,
  день,
  днейВМесяце,
  дниПериода,
  периодИз,
  полнаяДата,
  ужатьЧисло,
} from '../reportFilter';

/**
 * Окно «Дата» в отчёте — по снимку Вазгена.
 *
 * Сверху две вкладки, «Начало периода» и «Конец периода», под ними
 * колёсико из чисел, месяцев и годов, кнопка «Применить», а ниже список
 * готовых периодов: Сегодня, Вчера, Неделя, Месяц, Прошлый месяц, Год.
 */

// Нижний Новгород: +3 часа. Так же считает и запрос.
const МСК = 180;

describe('период из двух дат', () => {
  it('начинается местной полуночью и кончается последней секундой', () => {
    const период = периодИз('2026-09-01', '2026-09-30', МСК);

    // Полночь 1 сентября в Нижнем — это 21:00 31 августа по Гринвичу.
    expect(период.from).toBe('2026-08-31T21:00:00.000Z');
    expect(период.to).toBe('2026-09-30T20:59:59.999Z');
  });

  it('согласован с разбором дней: ровно те сутки, что выбрали', () => {
    // Главная проверка: конец периода не должен приводить лишний день.
    // Сдвинь его на полночь следующих суток — и здесь станет 31.
    const период = периодИз('2026-09-01', '2026-09-30', МСК);
    const дни = дниПериода(период.from, период.to, МСК);

    expect(дни).toHaveLength(30);
    expect(дни[0]).toBe('2026-09-01');
    expect(дни[29]).toBe('2026-09-30');
  });

  it('один день — это один день', () => {
    const период = периодИз('2026-03-04', '2026-03-04', МСК);
    expect(дниПериода(период.from, период.to, МСК)).toEqual(['2026-03-04']);
  });
});

describe('готовые периоды под календарём', () => {
  // Пятница 11 сентября 2026, полдень в Нижнем.
  const пятница = new Date('2026-09-11T09:00:00.000Z');
  const список = быстрыеПериоды(пятница, МСК);

  it('те же шесть и в том же порядке, что у него', () => {
    expect(список.map((один) => один.имя)).toEqual([
      'Сегодня',
      'Вчера',
      'Неделя',
      'Месяц',
      'Прошлый месяц',
      'Год',
    ]);
  });

  it('«Сегодня» подписано днём недели', () => {
    const сегодня = список[0];
    expect(сегодня.подпись).toBe('пятница');
    expect(сегодня.от).toBe('2026-09-11');
    expect(сегодня.до).toBe('2026-09-11');
  });

  it('«Вчера» — это четверг, и он один день, а не два', () => {
    const вчера = список[1];
    expect(вчера.подпись).toBe('четверг');
    expect(вчера.от).toBe('2026-09-10');
    expect(вчера.до).toBe('2026-09-10');
  });

  it('неделя считается с понедельника', () => {
    const неделя = список[2];
    expect(неделя.от).toBe('2026-09-07');
    expect(неделя.до).toBe('2026-09-13');
    expect(неделя.подпись).toBe('7 сент. – 13 сент.');
  });

  it('месяц — от первого до последнего числа', () => {
    const месяц = список[3];
    expect(месяц.подпись).toBe('сентябрь');
    expect(месяц.от).toBe('2026-09-01');
    expect(месяц.до).toBe('2026-09-30');
  });

  it('прошлый месяц — весь август, а не тридцать дней назад', () => {
    const прошлый = список[4];
    expect(прошлый.подпись).toBe('август');
    expect(прошлый.от).toBe('2026-08-01');
    expect(прошлый.до).toBe('2026-08-31');
  });

  it('год — от первого января до тридцать первого декабря', () => {
    const год = список[5];
    expect(год.подпись).toBe('2026');
    expect(год.от).toBe('2026-01-01');
    expect(год.до).toBe('2026-12-31');
  });

  it('в январе «прошлый месяц» уходит в декабрь прошлого года', () => {
    const январь = быстрыеПериоды(new Date('2026-01-15T09:00:00.000Z'), МСК);
    const прошлый = январь.find((один) => один.ключ === 'прошлый')!;

    expect(прошлый.подпись).toBe('декабрь');
    expect(прошлый.от).toBe('2025-12-01');
    expect(прошлый.до).toBe('2025-12-31');
  });

  it('неделя, начавшаяся в прошлом месяце, не обрезается', () => {
    // Вторник 1 сентября 2026: неделя началась в понедельник 31 августа.
    const вторник = быстрыеПериоды(new Date('2026-09-01T09:00:00.000Z'), МСК);
    const неделя = вторник.find((один) => один.ключ === 'неделя')!;

    expect(неделя.от).toBe('2026-08-31');
    expect(неделя.до).toBe('2026-09-06');
  });

  it('в воскресенье неделя ещё та же самая, а не следующая', () => {
    // Воскресенье 13 сентября 2026 — последний день недели с 7-го.
    const воскресенье = быстрыеПериоды(new Date('2026-09-13T09:00:00.000Z'), МСК);
    const неделя = воскресенье.find((один) => один.ключ === 'неделя')!;

    expect(неделя.от).toBe('2026-09-07');
    expect(неделя.до).toBe('2026-09-13');
  });

  it('после полуночи по местному сегодня уже новое', () => {
    // 00:30 в Нижнем 11 сентября — это 21:30 десятого по Гринвичу.
    const ночью = быстрыеПериоды(new Date('2026-09-10T21:30:00.000Z'), МСК);
    expect(ночью[0].от).toBe('2026-09-11');
    expect(ночью[1].от).toBe('2026-09-10');
  });
});

describe('колёсико чисел', () => {
  it('знает, сколько дней в месяце, включая февраль', () => {
    expect(днейВМесяце(2026, 2)).toBe(28);
    expect(днейВМесяце(2024, 2)).toBe(29);
    expect(днейВМесяце(2026, 9)).toBe(30);
    expect(днейВМесяце(2026, 12)).toBe(31);
  });

  it('31 марта при переходе на февраль становится 28, а не 3 марта', () => {
    expect(ужатьЧисло(2026, 2, 31)).toBe(28);
    expect(ужатьЧисло(2024, 2, 31)).toBe(29);
    // А то, что помещается, не трогаем.
    expect(ужатьЧисло(2026, 3, 31)).toBe(31);
  });
});

describe('подписи дат', () => {
  it('«4 марта 2026» — так подписана вкладка «Конец периода»', () => {
    expect(полнаяДата('2026-03-04')).toBe('4 марта 2026');
    expect(полнаяДата('2026-01-01')).toBe('1 января 2026');
  });

  it('местная дата мгновения берётся со сдвигом', () => {
    expect(день(new Date('2026-09-10T21:30:00.000Z'), МСК)).toBe('2026-09-11');
    expect(день(new Date('2026-09-10T20:30:00.000Z'), МСК)).toBe('2026-09-10');
  });
});
