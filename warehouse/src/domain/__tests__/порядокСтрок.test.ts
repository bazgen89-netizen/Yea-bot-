import { порядокСтрок, числоИзЯчейки } from '../reportFilter';

/**
 * Порядок строк отчёта.
 *
 * Вазген: «если у нас идёт продажа по дням, то дни строго по возрастанию
 * или убыванию, а они вперемешку». Так и было: сортировка сравнивала
 * подписи как текст, и сентябрь вставал 1, 10, 11, 2, 30, 9.
 */
describe('дни идут подряд', () => {
  const дни = [
    ['1 сентября', '100'],
    ['2 сентября', '200'],
    ['9 сентября', '900'],
    ['10 сентября', '50'],
    ['11 сентября', '0'],
    ['30 сентября', '0'],
  ];

  it('по возрастанию — как отдал запрос, а не по алфавиту', () => {
    const вышло = порядокСтрок(дни, {
      колонка: 0,
      вверх: true,
      числовая: false,
      поПорядку: true,
    });

    expect(вышло.map((строка) => строка[0])).toEqual([
      '1 сентября',
      '2 сентября',
      '9 сентября',
      '10 сентября',
      '11 сентября',
      '30 сентября',
    ]);
  });

  it('по убыванию — от последнего дня к первому', () => {
    const вышло = порядокСтрок(дни, {
      колонка: 0,
      вверх: false,
      числовая: false,
      поПорядку: true,
    });

    expect(вышло.map((строка) => строка[0])).toEqual([
      '30 сентября',
      '11 сентября',
      '10 сентября',
      '9 сентября',
      '2 сентября',
      '1 сентября',
    ]);
  });

  it('сравнение букв на этих же днях врёт — ради этого всё и сделано', () => {
    const побуквенно = порядокСтрок(дни, {
      колонка: 0,
      вверх: true,
      числовая: false,
      поПорядку: false,
    });

    // Вот что видел Вазген.
    expect(побуквенно.map((строка) => строка[0])).toEqual([
      '1 сентября',
      '10 сентября',
      '11 сентября',
      '2 сентября',
      '30 сентября',
      '9 сентября',
    ]);
  });
});

describe('порядок по названию', () => {
  const товары = [
    ['Ба Сянь Дань Цун', '631,90'],
    ['Ань Цзи Бай Ча', '774'],
    ['ёжик', '1'],
    ['Алишань', '12'],
  ];

  it('по-русски: «ё» стоит после «е», а не в конце азбуки', () => {
    const вышло = порядокСтрок(товары, {
      колонка: 0,
      вверх: true,
      числовая: false,
      поПорядку: false,
    });

    expect(вышло.map((строка) => строка[0])).toEqual([
      'Алишань',
      'Ань Цзи Бай Ча',
      'Ба Сянь Дань Цун',
      'ёжик',
    ]);
  });
});

describe('порядок по числам', () => {
  const строки = [
    ['Первый', '9 980'],
    ['Второй', '516'],
    ['Третий', '2 600'],
    ['Четвёртый', '147,50'],
  ];

  it('числа сравниваются числами, а не буквами', () => {
    // Буквами «516» встало бы раньше «9 980», а по величине — наоборот.
    const вышло = порядокСтрок(строки, {
      колонка: 1,
      вверх: false,
      числовая: true,
      поПорядку: false,
    });

    expect(вышло.map((строка) => строка[0])).toEqual([
      'Первый',
      'Третий',
      'Второй',
      'Четвёртый',
    ]);
  });

  it('равные числа сохраняют прежнее место, а не прыгают', () => {
    const одинаковые = [
      ['А', '0'],
      ['Б', '0'],
      ['В', '0'],
    ];
    const вышло = порядокСтрок(одинаковые, {
      колонка: 1,
      вверх: true,
      числовая: true,
      поПорядку: false,
    });

    expect(вышло.map((строка) => строка[0])).toEqual(['А', 'Б', 'В']);
  });

  it('исходный список не переставляется на месте', () => {
    const было = [...строки];
    порядокСтрок(строки, { колонка: 1, вверх: true, числовая: true, поПорядку: false });
    expect(строки).toEqual(было);
  });
});

describe('число из ячейки', () => {
  it('понимает оба формата и проценты', () => {
    expect(числоИзЯчейки('26,525.60')).toBeCloseTo(26525.6);
    expect(числоИзЯчейки('9 980')).toBe(9980);
    expect(числоИзЯчейки('894%')).toBe(894);
    expect(числоИзЯчейки('-351')).toBe(-351);
  });

  it('не-число — ноль, а не NaN', () => {
    // NaN в сравнении ломает весь порядок: он не больше и не меньше ничего.
    expect(числоИзЯчейки('Габа Алишань')).toBe(0);
    expect(числоИзЯчейки('')).toBe(0);
  });
});
