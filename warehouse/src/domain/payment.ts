import type { Kopecks } from './money';

/**
 * Оплата чека.
 *
 * Главное здесь — подсказки «Варианты оплаты наличными»: ряд кнопок с
 * суммами, которые покупатель скорее всего протянет. Кассир не считает сдачу
 * в уме и не набирает сумму цифрами — он нажимает ту купюру, что дали.
 *
 * Правило составления взято из их кассы дословно. Оно неочевидное, поэтому
 * стоит объяснить: берётся сама сумма, округлённая вверх до рубля, и дальше
 * четыре круга — по десяткам, сотням, тысячам и десяткам тысяч. В каждом
 * круге сумма урезается вниз до этого разряда, и к ней прибавляются три
 * ступени: 2/5/10 в десятках, 20/50/100 в сотнях и так далее. Годятся только
 * те, что больше самой суммы.
 *
 * Единственное исключение — их же: если чек меньше ста рублей, третья ступень
 * каждого круга пропускается. Иначе на чек в 33 рубля предлагалось бы «40»,
 * что никто не даёт, — дают полтинник.
 *
 * На мелком чеке хвост получается крупный: для 33 рублей выходит
 * 33 · 35 · 50 · 200 · 500 · 2000 · 5000. Так считает и их касса — кнопки
 * стоят в прокручиваемом ряду, и дальние просто не попадают в глаза.
 */

/** Ступени, которые прибавляются к урезанной сумме в каждом круге. */
const STEPS = [
  [2, 5, 10],
  [20, 50, 100],
  [200, 500, 1000],
  [2000, 5000, 10000],
];

/**
 * Подсказки оплаты наличными, копейки, по возрастанию.
 *
 * Считается в рублях, потому что купюры — рублёвые: ступень «5» означает
 * пятирублёвую монету, а не пять копеек.
 */
export function cashOptions(total: Kopecks): Kopecks[] {
  const rubles = total / 100;
  const found = new Set<number>();

  // Сама сумма, округлённая вверх до рубля. Ноль добавляется дважды — сам
  // и как копейка: так у них, и на нулевом чеке остаётся хоть одна кнопка.
  found.add(Math.ceil(rubles));
  found.add(Math.ceil(rubles === 0 ? 0.01 : rubles));

  for (let round = 0; round < STEPS.length; round++) {
    const scale = Math.pow(10, round + 1);
    const floor = Math.floor(rubles / scale) * scale;
    if (floor === rubles) continue;

    for (let step = 0; step < STEPS[round].length; step++) {
      // Их исключение: на чеке меньше ста рублей третья ступень круга
      // пропускается. На чек в 33 рубля не предлагается «40» — таких купюр не
      // дают, дают полтинник.
      const skip = rubles < 100 && step === 2;
      const option = floor + STEPS[round][step];
      if (option > rubles && !skip) found.add(Math.ceil(option));
    }
  }

  return [...found].sort((a, b) => a - b).map((value) => Math.round(value * 100));
}

/** Сдача: сколько вернуть. Меньше суммы чека — сдачи нет. */
export function change(tendered: Kopecks, total: Kopecks): Kopecks {
  return Math.max(0, tendered - total);
}

/** Хватает ли внесённого, чтобы закрыть чек. */
export function enough(tendered: Kopecks, total: Kopecks): boolean {
  return tendered >= total;
}
