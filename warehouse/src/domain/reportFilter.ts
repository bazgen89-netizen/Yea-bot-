/**
 * Отбор в отчёте на телефоне: дни периода и подписи на фишках.
 *
 * Здесь нет ни React, ни базы — только арифметика дат и склейка подписей.
 * Экран её не считает сам: иначе «1 – 30 сент.» невозможно проверить, не
 * открыв телефон.
 */

/** Отбор, по которому строится отчёт. Пустые поля значат «все». */
export interface ОтборОтчёта {
  /** Магазин; null — все три. */
  место: number | null;
  /** Сотрудник; null — все. */
  сотрудник: number | null;
  /** Покупатель; null — все. Есть не во всех отчётах — только там, где чек. */
  клиент: number | null;
}

export const ПУСТОЙ_ОТБОР: ОтборОтчёта = { место: null, сотрудник: null, клиент: null };

/** Что-нибудь выбрано — значит фишку «Очистить» есть смысл показывать. */
export function естьОтбор(отбор: ОтборОтчёта): boolean {
  return отбор.место !== null || отбор.сотрудник !== null || отбор.клиент !== null;
}

const МЕСЯЦЫ = [
  'янв.', 'февр.', 'марта', 'апр.', 'мая', 'июня',
  'июля', 'авг.', 'сент.', 'окт.', 'нояб.', 'дек.',
];

/** «сент.» — тот же список, но в именительном: для «1 – 30 сент.». */
const МЕСЯЦЫ_КОРОТКО = [
  'янв.', 'февр.', 'март', 'апр.', 'май', 'июнь',
  'июль', 'авг.', 'сент.', 'окт.', 'нояб.', 'дек.',
];

/**
 * Сдвинуть мгновение к местному времени и отрезать дату.
 *
 * Ровно то же, что делает `localDaySql` в запросе: сперва прибавляем сдвиг
 * часового пояса, потом берём дату по Гринвичу. Иначе чек, пробитый в
 * половине первого ночи, попадал бы во вчерашний день — а в списке дней
 * его бы не было вовсе.
 */
function местныйДень(миг: string, сдвигМинут: number): string {
  const дата = new Date(new Date(миг).getTime() + сдвигМинут * 60_000);
  return дата.toISOString().slice(0, 10);
}

/**
 * Все дни периода подряд — включая те, когда не торговали.
 *
 * У него в отчёте стоят все тридцать дней месяца, и двадцать девятое
 * сентября с нулём — такая же строка, как остальные: видно, что в этот день
 * не торговали, а не что его забыли посчитать. Запрос же отдаёт только дни
 * с чеками, и без этого списка отчёт за месяц показывал бы десять строк
 * вместо тридцати, а «Итог (30 позиций)» превращался бы в «Итог (10)».
 */
export function дниПериода(
  от: string,
  до: string,
  сдвигМинут = -new Date().getTimezoneOffset(),
): string[] {
  const первый = местныйДень(от, сдвигМинут);
  const последний = местныйДень(до, сдвигМинут);
  if (последний < первый) return [];

  const дни: string[] = [];
  // Шагаем по UTC-полудню: полночь в паре с летним временем умеет
  // перепрыгнуть день, а полдень — нет.
  const шаг = new Date(`${первый}T12:00:00.000Z`);
  const край = new Date(`${последний}T12:00:00.000Z`);

  while (шаг.getTime() <= край.getTime()) {
    дни.push(шаг.toISOString().slice(0, 10));
    шаг.setUTCDate(шаг.getUTCDate() + 1);
    // Страховка от бесконечности, если границы вдруг придут порченые.
    if (дни.length > 4000) break;
  }
  return дни;
}

/**
 * Подпись на фишке даты: «1 – 30 сент.», «28 авг. – 3 сент.», «11 сент.».
 *
 * Месяц не повторяется дважды, когда он один и тот же: у него на фишке
 * «1 - 30 сент.», а не «1 сент. - 30 сент.» — на узкой фишке лишние шесть
 * знаков вытесняют остальные.
 */
export function подписьПериода(
  от: string,
  до: string,
  сдвигМинут = -new Date().getTimezoneOffset(),
): string {
  const первый = местныйДень(от, сдвигМинут);
  const последний = местныйДень(до, сдвигМинут);
  if (последний < первый) return '—';

  const [гА, мА, дА] = первый.split('-').map(Number);
  const [гБ, мБ, дБ] = последний.split('-').map(Number);

  if (первый === последний) return `${дА} ${МЕСЯЦЫ[мА - 1]}`;

  // Весь год целиком — так он и подписан, без дней.
  if (мА === 1 && дА === 1 && мБ === 12 && дБ === 31 && гА === гБ) return `${гА} год`;

  if (гА === гБ && мА === мБ) return `${дА} – ${дБ} ${МЕСЯЦЫ_КОРОТКО[мА - 1]}`;
  if (гА === гБ) return `${дА} ${МЕСЯЦЫ_КОРОТКО[мА - 1]} – ${дБ} ${МЕСЯЦЫ_КОРОТКО[мБ - 1]}`;
  return `${дА} ${МЕСЯЦЫ_КОРОТКО[мА - 1]} ${гА} – ${дБ} ${МЕСЯЦЫ_КОРОТКО[мБ - 1]} ${гБ}`;
}

/** «30 сентября» — подпись строки в самом отчёте, как у него. */
const МЕСЯЦЫ_РОДИТ = [
  'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря',
];

export function подписьДня(день: string): string {
  const [, месяц, число] = день.split('-').map(Number);
  if (!месяц || !число) return день;
  return `${число} ${МЕСЯЦЫ_РОДИТ[месяц - 1]}`;
}

/**
 * Порядок строк отчёта.
 *
 * Вынесено сюда из экрана, потому что на этом я уже ошибся. Сортировка
 * сравнивала подписи как текст, и «Продажи по дням» вставали так:
 * 1, 10, 11, 2, 30, 9 сентября. Вазген это и увидел: «дни строго по
 * возрастанию или убыванию, а они вперемешку».
 *
 * У отчёта по датам подписи — не названия, а даты, и сравнивать их
 * буквами нельзя вовсе. Запрос отдаёт их по порядку, поэтому для первой
 * колонки таких отчётов порядком служит сам порядок строк: развернуть его
 * — значит показать от последнего дня к первому, а не переставить буквы.
 */
export function порядокСтрок(
  строки: string[][],
  правило: {
    колонка: number;
    вверх: boolean;
    /** Колонка числовая — сравниваем числа, а не буквы. */
    числовая: boolean;
    /** Отчёт по датам, и сортируем по первой колонке — идём по порядку строк. */
    поПорядку: boolean;
  },
): string[][] {
  const знак = правило.вверх ? 1 : -1;

  // Помним, где строка стояла: `sort` в JS устойчив, но нам нужен сам
  // номер, а не только устойчивость.
  const сНомерами = строки.map((строка, номер) => ({ строка, номер }));

  сНомерами.sort((а, б) => {
    if (правило.поПорядку) return (а.номер - б.номер) * знак;

    const левое = а.строка[правило.колонка] ?? '';
    const правое = б.строка[правило.колонка] ?? '';

    if (правило.числовая) {
      const разница = числоИзЯчейки(левое) - числоИзЯчейки(правое);
      // Равные числа — по прежнему месту, иначе список дрожит при каждом
      // перерисовывании.
      return разница !== 0 ? разница * знак : а.номер - б.номер;
    }

    const сравнение = левое.localeCompare(правое, 'ru');
    return сравнение !== 0 ? сравнение * знак : а.номер - б.номер;
  });

  return сНомерами.map((один) => один.строка);
}

/**
 * Число из готовой ячейки: «26,525.60» и «894%» — в 26525.6 и 894.
 *
 * Ячейки отчёта — уже текст, второго, «сырого» набора значений рядом нет.
 * Держать его значило бы иметь два источника правды об одном столбце.
 */
export function числоИзЯчейки(ячейка: string): number {
  // Убираем всё, что не цифра, не знак и не разделитель.
  const без = ячейка.replace(/[\s\u00A0%]/g, '');

  /*
   * Запятая значит разное в двух форматах, и спутать их — ошибиться в сто
   * раз.
   *
   * Кабинет пишет «26,525.60»: запятая делит тысячи, точка — копейки.
   * Телефон пишет «26 525,60»: тысячи делит пробел, копейки — запятая.
   * Первая же проверка на этом меня и поймала: «147,50» я посчитал как
   * четырнадцать тысяч семьсот пятьдесят, и в сортировке по выручке эта
   * строка ушла наверх.
   *
   * Различаем по точке: если она есть — она и есть копейки, а запятые
   * тогда тысячи. Точки нет — запятая остаётся единственной кандидаткой
   * на копейки.
   */
  const чистое = без.includes('.') ? без.replace(/,/g, '') : без.replace(',', '.');

  const значение = Number(чистое);
  return Number.isFinite(значение) ? значение : 0;
}

/** Полные названия месяцев в именительном: «сентябрь» под строкой «Месяц». */
const МЕСЯЦЫ_ПОЛНЫЕ = [
  'январь', 'февраль', 'март', 'апрель', 'май', 'июнь',
  'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь',
];

/** Дни недели: «пятница» под строкой «Сегодня». Воскресенье у Date — ноль. */
const ДНИ_НЕДЕЛИ = [
  'воскресенье', 'понедельник', 'вторник', 'среда',
  'четверг', 'пятница', 'суббота',
];

/** «2026-09-11» — местная дата этого мгновения. */
export function день(миг: Date, сдвигМинут = -new Date().getTimezoneOffset()): string {
  return new Date(миг.getTime() + сдвигМинут * 60_000).toISOString().slice(0, 10);
}

/**
 * Период из двух местных дат: с первой полуночи по последнюю секунду.
 *
 * Конец — 23:59:59.999, а не полночь следующего дня. Так же его строит
 * `periodFor`, и так же его читает `дниПериода`: сдвинь конец на сутки
 * вперёд — и в списке дней появится лишний, а «Итог (30 позиций)» станет
 * тридцать первой.
 */
export function периодИз(
  отДня: string,
  доДня: string,
  сдвигМинут = -new Date().getTimezoneOffset(),
): { from: string; to: string } {
  const [гА, мА, дА] = отДня.split('-').map(Number);
  const [гБ, мБ, дБ] = доДня.split('-').map(Number);
  const сдвиг = сдвигМинут * 60_000;

  return {
    from: new Date(Date.UTC(гА, мА - 1, дА, 0, 0, 0, 0) - сдвиг).toISOString(),
    to: new Date(Date.UTC(гБ, мБ - 1, дБ, 23, 59, 59, 999) - сдвиг).toISOString(),
  };
}

/** Готовый период из списка под календарём. */
export interface БыстрыйПериод {
  ключ: string;
  имя: string;
  /** Серая строка под именем: «пятница», «7 сент. – 13 сент.», «2026». */
  подпись: string;
  от: string;
  до: string;
}

/**
 * Список под календарём — тот же и в том же порядке, что у него.
 *
 * «Прошлый месяц» здесь не роскошь: за ним лезут чаще всего, а набирать
 * колёсиком первое и последное число августа — шесть движений вместо
 * одного.
 */
export function быстрыеПериоды(
  сейчас = new Date(),
  сдвигМинут = -new Date().getTimezoneOffset(),
): БыстрыйПериод[] {
  // Считаем в местных сутках: берём местную дату и дальше двигаем её по UTC,
  // чтобы переход на летнее время не перепрыгнул день.
  const сегодня = день(сейчас, сдвигМинут);
  const [г, м, д] = сегодня.split('-').map(Number);
  const опора = new Date(Date.UTC(г, м - 1, д, 12));

  const какДень = (дата: Date) => дата.toISOString().slice(0, 10);
  const сдвинуть = (дней: number) => {
    const копия = new Date(опора.getTime());
    копия.setUTCDate(копия.getUTCDate() + дней);
    return копия;
  };

  const вчера = сдвинуть(-1);

  // Неделя с понедельника: getUTCDay() отдаёт воскресенье нулём.
  const кПонедельнику = (опора.getUTCDay() + 6) % 7;
  const началоНедели = сдвинуть(-кПонедельнику);
  const конецНедели = сдвинуть(6 - кПонедельнику);

  const первоеЭтого = новыйДень(г, м, 1);
  const последнееЭтого = новыйДень(г, м + 1, 0);
  const первоеПрошлого = новыйДень(г, м - 1, 1);
  const последнееПрошлого = новыйДень(г, м, 0);

  return [
    { ключ: 'сегодня', имя: 'Сегодня', подпись: ДНИ_НЕДЕЛИ[опора.getUTCDay()], от: сегодня, до: сегодня },
    { ключ: 'вчера', имя: 'Вчера', подпись: ДНИ_НЕДЕЛИ[вчера.getUTCDay()], от: какДень(вчера), до: какДень(вчера) },
    {
      ключ: 'неделя',
      имя: 'Неделя',
      подпись: `${подписьКоротко(какДень(началоНедели))} – ${подписьКоротко(какДень(конецНедели))}`,
      от: какДень(началоНедели),
      до: какДень(конецНедели),
    },
    {
      ключ: 'месяц',
      имя: 'Месяц',
      подпись: МЕСЯЦЫ_ПОЛНЫЕ[м - 1],
      от: первоеЭтого,
      до: последнееЭтого,
    },
    {
      ключ: 'прошлый',
      имя: 'Прошлый месяц',
      подпись: МЕСЯЦЫ_ПОЛНЫЕ[Number(первоеПрошлого.split('-')[1]) - 1],
      от: первоеПрошлого,
      до: последнееПрошлого,
    },
    { ключ: 'год', имя: 'Год', подпись: String(г), от: `${г}-01-01`, до: `${г}-12-31` },
  ];
}

/**
 * Дата по номерам, где месяц и день могут вылезать за границы.
 *
 * `Date.UTC(2026, 12, 0)` — это 31 декабря 2026, а `Date.UTC(2026, -1, 1)` —
 * 1 декабря 2025. На этом и держится «последнее число месяца»: нулевой день
 * следующего. Считать «тридцать или тридцать один» руками, помня про
 * февраль и високосный год, — лишний повод ошибиться.
 */
function новыйДень(год: number, месяц: number, день: number): string {
  return new Date(Date.UTC(год, месяц - 1, день, 12)).toISOString().slice(0, 10);
}

/** «7 сент.» — для подписи недели. */
function подписьКоротко(деньСтрокой: string): string {
  const [, месяц, число] = деньСтрокой.split('-').map(Number);
  return `${число} ${МЕСЯЦЫ_КОРОТКО[месяц - 1]}`;
}

/**
 * Сколько дней в месяце: колёсико не должно предлагать 31 февраля.
 *
 * Нулевой день следующего месяца — последний день этого, и високосный год
 * считается сам.
 */
export function днейВМесяце(год: number, месяц: number): number {
  return new Date(Date.UTC(год, месяц, 0)).getUTCDate();
}

/**
 * Подтянуть число к последнему существующему.
 *
 * Стояло 31 марта, покрутили месяц на февраль — 31 февраля не бывает, и
 * без этого выбор молча уехал бы на 3 марта.
 */
export function ужатьЧисло(год: number, месяц: number, число: number): number {
  return Math.min(число, днейВМесяце(год, месяц));
}

/** «4 марта 2026» — подпись под вкладкой «Конец периода». */
export function полнаяДата(деньСтрокой: string): string {
  const [год, месяц, число] = деньСтрокой.split('-').map(Number);
  if (!год || !месяц) return деньСтрокой;
  return `${число} ${МЕСЯЦЫ_РОДИТ[месяц - 1]} ${год}`;
}

/**
 * Кабинетное число — в телефонное: «26,525.60» → «26 525,60».
 *
 * Форматов в программе два, и это не недосмотр: на экранах кабинета суммы
 * записаны по-английски, а на телефоне — по-русски, и обе половины
 * повторяют то, что видит пользователь. Но ячейки отчёта готовятся один
 * раз на обе половины, кабинетным `formatMoneyWeb`, — и на телефоне
 * выходило «26,525.60» там, где у него «26 525,60».
 *
 * Переводим здесь, а не протаскиваем второй форматировщик через все
 * одиннадцать отчётов: там пришлось бы трогать каждую строку каждого
 * отчёта, а это одиннадцать поводов разойтись вместо одного.
 *
 * Не-числа проходят насквозь: «894%» и «12» остаются собой — в них нет ни
 * запятой-разделителя, ни точки.
 */
export function поРусски(ячейка: string): string {
  // Только то, что целиком число: «Габа Алишань, 100 гр» трогать нельзя.
  if (!/^-?[\d,]+(\.\d+)?%?$/.test(ячейка)) return ячейка;
  return ячейка.replace(/,/g, NBSP).replace('.', ',');
}

/** Неразрывный пробел: иначе «26 525,60» переносится посреди числа. */
const NBSP = ' ';

/**
 * Рубли и копейки врозь: «121 076» и «,51».
 *
 * У него копейки в итоговой строке набраны мельче и бледнее — на них не
 * смотрят, а место они занимают. Разделять строку на экране регулярным
 * выражением значило бы делать это в каждой такой строке заново.
 */
export function рублиИкопейки(сумма: string): [string, string] {
  const запятая = сумма.lastIndexOf(',');
  if (запятая < 0) return [сумма, ''];
  return [сумма.slice(0, запятая), сумма.slice(запятая)];
}

/**
 * Ячейка отчёта, разбитая для показа: целая часть и бледная дробная.
 *
 * Делает три вещи разом, потому что порядок важен: сперва перевести
 * кабинетный формат в русский, потом отрезать дробь, и только потом решать,
 * показывать ли её.
 *
 * Круглые суммы показываются без копеек: у него в отчёте по товарам стоит
 * «550» и «75», а рядом «785,52» и «479,20». То есть отбрасываются не
 * нули вообще — «479,20» свой ноль сохраняет, — а ровно нулевая дробь.
 *
 * Нулевая она из двух знаков или из трёх, неважно: количества выводятся
 * тысячными, и «0,000» в отчёте по движению — тот же ноль, что «0,00» в
 * денежном. Проверка ровно на «,00» его пропускала, и весь столбец
 * «Начальный остаток» стоял забитый нулями с хвостами.
 */
export function ячейкаОтчёта(ячейка: string): [string, string] {
  const русское = поРусски(ячейка);
  const [целое, дробь] = рублиИкопейки(русское);
  return /^,0+$/.test(дробь) ? [целое, ''] : [целое, дробь];
}
