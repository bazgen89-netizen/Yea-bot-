/**
 * Градиент полосами.
 *
 * В React Native плавного перехода нет, а `react-native-web` переводит стили
 * в inline-CSS, куда `linear-gradient` не попадает. Поэтому заливка шапки
 * набирается полосами одинаковой ширины — по цвету на полосу.
 *
 * Цвет полосы берётся **из середины** её отрезка, а не с края: полоса красится
 * целиком одним тоном, и середина — то, чем она была бы в плавном переходе
 * «в среднем». Взяв цвет с края, весь градиент уезжает на полполосы.
 *
 * Числа здесь не выдуманы: восемь полос, которыми шапка была набрана руками
 * (`#0285CE` … `#015A9E`), эта формула воспроизводит в точности — на этом
 * стоит тест. Оттого её и можно было завести: она не меняет прежний вид,
 * зато позволяет тому же коду нарисовать шапку нового кабинета, у которого
 * градиент другой — `linear-gradient(310deg, #1E40AF, #2563EB)`.
 */

/** «#01579B» → [1, 87, 155]. Иное на входе — исключение, а не тихий чёрный. */
function разобрать(цвет: string): [number, number, number] {
  const знаки = цвет.replace('#', '');
  if (!/^[0-9a-fA-F]{6}$/.test(знаки)) {
    throw new Error(`Цвет «${цвет}» не шестизначный шестнадцатеричный`);
  }
  return [
    parseInt(знаки.slice(0, 2), 16),
    parseInt(знаки.slice(2, 4), 16),
    parseInt(знаки.slice(4, 6), 16),
  ];
}

const двумя = (число: number) => число.toString(16).padStart(2, '0').toUpperCase();

/**
 * Полосы перехода от одного цвета к другому.
 *
 * @param откуда цвет первой полосы, «#RRGGBB»
 * @param куда   цвет последней полосы, «#RRGGBB»
 * @param сколько число полос; меньше одной не бывает
 */
export function полосыГрадиента(откуда: string, куда: string, сколько = 8): string[] {
  if (!Number.isInteger(сколько) || сколько < 1) {
    throw new Error(`Полос должно быть целое число и хотя бы одна, а не ${сколько}`);
  }

  const начало = разобрать(откуда);
  const конец = разобрать(куда);

  return Array.from({ length: сколько }, (_, номер) => {
    const доля = (номер + 0.5) / сколько;
    const канал = (к: 0 | 1 | 2) => двумя(Math.round(начало[к] + (конец[к] - начало[к]) * доля));
    return `#${канал(0)}${канал(1)}${канал(2)}`;
  });
}
