/**
 * Какой кабинет показывать — прежний или новый.
 *
 * У CloudShop сейчас две версии кабинета сразу, и пользователь ходит между
 * ними сам: в прежнем боковое меню предлагает «Перейти на новую версию», в
 * новом — «Вернуться к старой версии». Формулировки не сочинены: они взяты
 * из их же файла переводов `translator.cloudshop.ru/WAPP/ru.json`, ключи
 * `NEW_VERSION_MENU` и `WEBAPP_RETURN_TO_OLD_VERSION`.
 *
 * Выбор запоминается в браузере и переживает перезагрузку: человек выбрал
 * вид один раз, а не выбирает его каждое утро.
 *
 * **Почему переключение перезагружает страницу.** `StyleSheet.create`
 * вычисляет стили один раз, при загрузке: подменить палитру на ходу нельзя,
 * уже созданные стили останутся прежними. Поэтому выбор пишется в хранилище
 * браузера, а страница перечитывается — и палитра подхватывается с самого
 * начала. У CloudShop, кстати, то же самое: переключение версии уводит на
 * другой адрес, `web-beta.cloudshop.ru`.
 */
export type ВерсияКабинета = 'старая' | 'новая';

const КЛЮЧ = 'wayshop:версия-кабинета';

/** Наши собственные хвосты в адресе — их при запоминании убираем. */
const НАШИ_ХВОСТЫ = ['v', 'version', 'версия', 't', 'theme', 'тема'];

/**
 * Адрес, с которого программу открыли.
 *
 * Нужен для перезагрузки. Программа — один файл `index.html`, лежащий по
 * адресу папки; все внутренние переходы рисуются на месте, а адрес в строке
 * браузера при этом меняется на `/sklad/catalog` и подобные. Такого файла на
 * сервере нет, и `location.reload()` со страницы каталога приводил на «не
 * найдено» — Вазген на это и напоролся, нажав солнце на внутреннем экране.
 *
 * Поэтому возвращаемся туда, откуда пришли: на адрес папки, каким он был при
 * первой загрузке, без наших хвостов `?v=` и `?t=`.
 */
const НАЧАЛЬНЫЙ_АДРЕС: string | null = (() => {
  const адрес = (globalThis as { location?: Location }).location;
  if (!адрес?.href) return null;

  try {
    const разобранный = new URL(адрес.href);
    for (const хвост of НАШИ_ХВОСТЫ) разобранный.searchParams.delete(хвост);
    разобранный.hash = '';
    return разобранный.toString();
  } catch {
    return адрес.href;
  }
})();

/**
 * Перечитать страницу так, чтобы она открылась.
 *
 * С внутреннего экрана — возвращаемся на адрес папки: обычная перезагрузка
 * там упирается в «страница не найдена». С самой папки — просто перечитываем.
 */
function перечитатьСтраницу(): void {
  const адрес = (globalThis as { location?: Location }).location;
  if (!адрес) return;

  if (НАЧАЛЬНЫЙ_АДРЕС && адрес.href !== НАЧАЛЬНЫЙ_АДРЕС) {
    адрес.href = НАЧАЛЬНЫЙ_АДРЕС;
    return;
  }
  адрес.reload?.();
}

/**
 * Что выбрано сейчас. По умолчанию — прежний вид: его Вазген утверждал
 * экран за экраном, и менять его молча, без спроса, нельзя.
 *
 * Хранилища может не быть вовсе — на телефоне, в тестах, в окне без доступа
 * к данным сайта. Тогда прежний вид, без разговоров.
 */
export function версияКабинета(): ВерсияКабинета {
  const изАдреса = версияИзАдреса();
  if (изАдреса) {
    запомнить(изАдреса);
    return изАдреса;
  }

  try {
    const хранилище = (globalThis as { localStorage?: Storage }).localStorage;
    return хранилище?.getItem(КЛЮЧ) === 'новая' ? 'новая' : 'старая';
  } catch {
    return 'старая';
  }
}

/**
 * Версия, заданная прямо в адресе: `?версия=новая` или `?v=new`.
 *
 * Нужна затем, что пункт меню человек может и не найти: боковое меню длинное,
 * на невысоком экране нижние строки уходят под сгиб и до них надо
 * доскроллить. Вазген так и не нашёл. А ссылка — это ссылка: открыл и попал.
 *
 * Заданное в адресе тут же запоминается, поэтому достаточно открыть один раз:
 * дальше кабинет откроется в том же виде и без хвоста в адресе.
 *
 * Латинские написания — не прихоть: адрес с кириллицей мессенджеры и почта
 * перекодируют в `%D0%B2%D0%B5...`, и он перестаёт быть читаемым глазами.
 */
function версияИзАдреса(): ВерсияКабинета | null {
  const адрес = (globalThis as { location?: Location }).location;
  const строка = `${адрес?.search ?? ''}${адрес?.hash ?? ''}`;
  if (!строка) return null;

  const найдено = /[?&#](?:версия|version|v)=([^&#]+)/i.exec(строка);
  if (!найдено) return null;

  const слово = decodeURIComponent(найдено[1]).toLowerCase();
  if (слово === 'новая' || слово === 'new' || слово === 'nov') return 'новая';
  if (слово === 'старая' || слово === 'old' || слово === 'star') return 'старая';
  return null;
}

function запомнить(версия: ВерсияКабинета): void {
  try {
    (globalThis as { localStorage?: Storage }).localStorage?.setItem(КЛЮЧ, версия);
  } catch {
    // Хранилища нет — значит выбор живёт только до перезагрузки. Это лучше,
    // чем не показать выбранное вовсе.
  }
}

/** Другая версия — та, на которую предлагаем перейти. */
export function другаяВерсия(): ВерсияКабинета {
  return версияКабинета() === 'новая' ? 'старая' : 'новая';
}

/** Подпись пункта меню — их слово в слово. */
export function подписьПерехода(): string {
  return другаяВерсия() === 'новая' ? 'Перейти на новую версию' : 'Вернуться к старой версии';
}

/**
 * Переключить и перечитать страницу.
 *
 * Если хранилище недоступно, выбор запомнить нечем — тогда и страницу
 * перезагружать незачем: она откроется в том же виде, и человек решит, что
 * кнопка сломана. Лучше не делать ничего.
 */
export function переключитьВерсию(на: ВерсияКабинета = другаяВерсия()): boolean {
  try {
    const хранилище = (globalThis as { localStorage?: Storage }).localStorage;
    if (!хранилище) return false;
    хранилище.setItem(КЛЮЧ, на);
  } catch {
    return false;
  }

  перечитатьСтраницу();
  return true;
}

/**
 * Тёмный вид — только у нового кабинета.
 *
 * Так и у них: в прежнем кабинете переключателя нет вовсе, в новом он стоит
 * в шапке луной, рядом с колокольчиком, и запоминается в `cs:theme`.
 */
export type ТемаКабинета = 'светлая' | 'тёмная';

const КЛЮЧ_ТЕМЫ = 'wayshop:тема-кабинета';

export function темаКабинета(): ТемаКабинета {
  // В прежнем виде тёмной темы нет — как и у них.
  if (версияКабинета() !== 'новая') return 'светлая';

  const изАдреса = темаИзАдреса();
  if (изАдреса) {
    try {
      (globalThis as { localStorage?: Storage }).localStorage?.setItem(КЛЮЧ_ТЕМЫ, изАдреса);
    } catch {
      // Не запомнилось — покажем хотя бы сейчас.
    }
    return изАдреса;
  }

  try {
    const хранилище = (globalThis as { localStorage?: Storage }).localStorage;
    return хранилище?.getItem(КЛЮЧ_ТЕМЫ) === 'тёмная' ? 'тёмная' : 'светлая';
  } catch {
    return 'светлая';
  }
}

function темаИзАдреса(): ТемаКабинета | null {
  const адрес = (globalThis as { location?: Location }).location;
  const строка = `${адрес?.search ?? ''}${адрес?.hash ?? ''}`;
  if (!строка) return null;

  const найдено = /[?&#](?:тема|theme|t)=([^&#]+)/i.exec(строка);
  if (!найдено) return null;

  const слово = decodeURIComponent(найдено[1]).toLowerCase();
  if (слово === 'тёмная' || слово === 'темная' || слово === 'dark') return 'тёмная';
  if (слово === 'светлая' || слово === 'light') return 'светлая';
  return null;
}

/** Переключить тёмное на светлое и обратно, с перечитыванием страницы. */
export function переключитьТему(на?: ТемаКабинета): boolean {
  const куда = на ?? (темаКабинета() === 'тёмная' ? 'светлая' : 'тёмная');
  try {
    const хранилище = (globalThis as { localStorage?: Storage }).localStorage;
    if (!хранилище) return false;
    хранилище.setItem(КЛЮЧ_ТЕМЫ, куда);
  } catch {
    return false;
  }

  перечитатьСтраницу();
  return true;
}

/** Адрес, открыв который попадаешь сразу в нужную версию. */
export function ссылкаНаВерсию(адресСайта: string, версия: ВерсияКабинета): string {
  const разделитель = адресСайта.includes('?') ? '&' : '?';
  return `${адресСайта}${разделитель}v=${версия === 'новая' ? 'new' : 'old'}`;
}
