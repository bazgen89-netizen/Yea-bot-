async def seed() -> None:
    await init_models()
    async with get_session() as session:
        for data in SCENARIOS:
            existing = await session.execute(
                select(GuestScenario).where(GuestScenario.question == data["question"])
            )
            scenario = existing.scalar_one_or_none()
            if scenario is None:
                session.add(GuestScenario(**data))
                continue
            # Сидер идёт на каждом старте: отредактированная подсказка должна
            # доехать до живой базы, а не остаться в коде.
            scenario.good_answer_points = data["good_answer_points"]
        await session.commit()


if __name__ == "__main__":
    asyncio.run(seed())
